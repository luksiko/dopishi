import XCTest
import AppKit
@testable import LangSwitcher

final class TransientPasteboardTests: XCTestCase {

    func testWriteTransientStringIncludesRequiredTypes() {
        let pasteboard = NSPasteboard.withUniqueName()
        let text = "test completion snippet"
        
        let changeCount = TransientPasteboard.writeString(text, pasteboard: pasteboard)
        XCTAssertGreaterThan(changeCount, 0)
        
        XCTAssertEqual(pasteboard.string(forType: .string), text)
        
        // Verify all transient and privacy markers are present
        let types = pasteboard.types ?? []
        XCTAssertTrue(types.contains(NSPasteboard.PasteboardType("org.nspasteboard.TransientType")))
        XCTAssertTrue(types.contains(NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")))
        XCTAssertTrue(types.contains(NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")))
        XCTAssertTrue(types.contains(NSPasteboard.PasteboardType("com.apple.quicktype.save-state")))
        XCTAssertTrue(types.contains(NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType")))
    }

    func testSnapshotAndRestore() {
        let pasteboard = NSPasteboard.withUniqueName()
        pasteboard.clearContents()
        pasteboard.setString("User original clipboard content", forType: .string)
        
        let snapshot = TransientPasteboard.snapshot(pasteboard: pasteboard)
        XCTAssertFalse(snapshot.isEmpty)
        
        // Overwrite with automated transient text
        TransientPasteboard.writeString("Temporary automated text", pasteboard: pasteboard)
        XCTAssertEqual(pasteboard.string(forType: .string), "Temporary automated text")
        
        // Restore snapshot
        TransientPasteboard.restore(snapshot, pasteboard: pasteboard)
        XCTAssertEqual(pasteboard.string(forType: .string), "User original clipboard content")
    }

    func testEmptySnapshotRestoreClearsContents() {
        let pasteboard = NSPasteboard.withUniqueName()
        pasteboard.clearContents()
        
        let emptySnapshot = TransientPasteboard.snapshot(pasteboard: pasteboard)
        XCTAssertTrue(emptySnapshot.isEmpty)
        
        TransientPasteboard.writeString("temporary", pasteboard: pasteboard)
        XCTAssertEqual(pasteboard.string(forType: .string), "temporary")
        
        TransientPasteboard.restore(emptySnapshot, pasteboard: pasteboard)
        XCTAssertNil(pasteboard.string(forType: .string))
    }
}
