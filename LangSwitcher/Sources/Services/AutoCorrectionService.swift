    init(settingsManager: SettingsManager,
         textConverter: TextConverter,
         accessibilityService: AccessibilityService = AccessibilityService(),
         spellCheckService: SpellCheckService = .shared,
         autocompletionEngine: AutocompletionEngine? = nil,
         overlayController: AutocompletionOverlayController? = nil,
         ghostTextController: GhostTextOverlayController? = nil,
         fieldAnchorController: FieldAnchorOverlayController? = nil,
         adaptiveStore: AutocompletionAdaptiveStore? = nil,
         completionRefresh: AutocompletionRefresh? = nil,
         acceptanceHandler: AcceptanceHandler? = nil) {
        self.acceptanceHandler = acceptanceHandler
        self.completionRefresh = completionRefresh ?? AutocompletionRefresh()
        self.settingsManager = settingsManager
        self.textConverter = textConverter
        self.accessibilityService = accessibilityService
        self.spellCheckService = spellCheckService
        let store = adaptiveStore ?? .shared
        self.adaptiveStore = store
        self.autocompletionEngine = autocompletionEngine ?? AutocompletionEngine(spellCheckService: spellCheckService, adaptiveStore: store)
        self.overlayController = overlayController ?? AutocompletionOverlayController()
        self.ghostTextController = ghostTextController ?? GhostTextOverlayController()
        self.fieldAnchorController = fieldAnchorController ?? FieldAnchorOverlayController()
        
        NotificationCenter.default.addObserver(
            self,
            selector: #selector(handleLayoutChanged),
            name: .keyboardLayoutSelectionChanged,
            object: nil
        )
        DistributedNotificationCenter.default().addObserver(
            self,
            selector: #selector(handleLayoutChanged),
            name: NSNotification.Name(kTISNotifySelectedKeyboardInputSourceChanged as String),
            object: nil
        )
        NSWorkspace.shared.notificationCenter.addObserver(
            self,
            selector: #selector(handleAppActivated),
            name: NSWorkspace.didActivateApplicationNotification,
            object: nil
        )
        NSWorkspace.shared.notificationCenter.addObserver(
            self,
            selector: #selector(handleAppDeactivated),
            name: NSWorkspace.didDeactivateApplicationNotification,
            object: nil
        )
    }

    deinit {
        NotificationCenter.default.removeObserver(self)
        DistributedNotificationCenter.default().removeObserver(self)
        NSWorkspace.shared.notificationCenter.removeObserver(self)
        if let monitor = globalMouseMonitor {
            NSEvent.removeMonitor(monitor)
            globalMouseMonitor = nil
        }
        if let monitor = localMouseMonitor {
            NSEvent.removeMonitor(monitor)
            localMouseMonitor = nil
        }
        if let tap = eventTap {
            CGEvent.tapEnable(tap: tap, enable: false)
            if let source = runLoopSource {
                CFRunLoopRemoveSource(CFRunLoopGetMain(), source, .commonModes)
            }
            CFMachPortInvalidate(tap)
        }
    }

    // MARK: - Public API

    /// Start monitoring keystrokes for auto-correction and autocompletion.
    /// Requires Accessibility permissions (same as existing hotkey functionality).
    func start() {
        guard settingsManager.needsKeyboardMonitoring else {
            ServiceStatus.shared.state = .disabled
            return
        }
        guard AccessibilityService.hasAccessibilityPermission else {
            ServiceStatus.shared.state = .permissionRequired
            return
        }
        guard eventTap == nil else {
            NSLog("[LangSwitcher] AutoCorrectionService: already started")
            return
        }

        // We need a pointer to self for the C callback.
        // Use Unmanaged to pass self as void pointer.
        let selfPtr = Unmanaged.passUnretained(self).toOpaque()

        // Observe releases too: a consumed acceptance key owns its repeat cycle.
        // Using .defaultTap so it works under Accessibility permissions (listenOnly requires Input Monitoring).
        // CRITICAL: Mouse events are monitored PASSIVELY via NSEvent monitors below.
        // Never put mouse events in CGEventTap to prevent WindowServer input deadlocks!
        let eventMask: CGEventMask = (1 << CGEventType.keyDown.rawValue) |
                                     (1 << CGEventType.keyUp.rawValue)

        guard let tap = CGEvent.tapCreate(
            tap: .cgSessionEventTap,
            place: .headInsertEventTap,
            options: .defaultTap,
            eventsOfInterest: eventMask,
            callback: autoCorrectionEventCallback,
            userInfo: selfPtr
        ) else {
            ServiceStatus.shared.state = .failed
            NSLog("[LangSwitcher] AutoCorrectionService: failed to create CGEvent tap. Check Accessibility permissions.")
            return
        }

        eventTap = tap

        let source = CFMachPortCreateRunLoopSource(kCFAllocatorDefault, tap, 0)
        runLoopSource = source
        CFRunLoopAddSource(CFRunLoopGetMain(), source, .commonModes)
        CGEvent.tapEnable(tap: tap, enable: true)

        if globalMouseMonitor == nil {
            globalMouseMonitor = NSEvent.addGlobalMonitorForEvents(
                matching: [.leftMouseDown, .rightMouseDown]
            ) { [weak self] _ in
                self?.handleMouseDown()
            }
        }
        if localMouseMonitor == nil {
            localMouseMonitor = NSEvent.addLocalMonitorForEvents(
                matching: [.leftMouseDown, .rightMouseDown]
            ) { [weak self] event in
                self?.handleMouseDown()
                return event
            }
        }

        ServiceStatus.shared.state = isRunning ? .running : .failed
        NSLog("[LangSwitcher] AutoCorrectionService: started keystroke monitoring")
    }

    /// Reconcile real tap state, including permission changes and invalid ports.
    func checkHealth() {
        let action = ServiceRecovery.action(
            enabled: settingsManager.needsKeyboardMonitoring,
            trusted: AccessibilityService.hasAccessibilityPermission,
            valid: eventTap.map { CFMachPortIsValid($0) } ?? false,
            running: isRunning
        )
        switch action {
        case .disable:
            if eventTap != nil { stop() }
            ServiceStatus.shared.state = .disabled
        case .waitForPermission:
            if eventTap != nil { stop() }
            ServiceStatus.shared.state = .permissionRequired
        case .start:
            stop()
            start()
        case .enable:
            wordBuffer = ""
            overlayController.hide()
            if let tap = eventTap { CGEvent.tapEnable(tap: tap, enable: true) }
            if isRunning {
                ServiceStatus.shared.state = .running
            } else {
                restart()
            }
        case .none:
            ServiceStatus.shared.state = .running
        }
    }

    func reEnableEventTap() {
        if let tap = eventTap {
            CGEvent.tapEnable(tap: tap, enable: true)
        }
        checkHealth()
    }

    /// Stop monitoring keystrokes.
    func stop() {
        consumedAcceptanceKeys.removeAll()
        completionRefresh.cancel()
        fieldAnchorDebounce.cancel()
        phraseContinuationAnchor = nil
        physicalInputRevision &+= 1
        replacementSession.cancel()
        accessibilityService.cancelPendingReplacement()
        overlayController.hide()
        ghostTextController.hide()
        activeGhostState = nil
        currentAIRequestId = nil
        typeAheadHandledCount = 0
        fieldAnchorController.hide()
        stopFieldAnchorPoll()
        if let monitor = globalMouseMonitor {
            NSEvent.removeMonitor(monitor)
            globalMouseMonitor = nil
        }
        if let monitor = localMouseMonitor {
            NSEvent.removeMonitor(monitor)
            localMouseMonitor = nil
        }
        if let tap = eventTap {
            CGEvent.tapEnable(tap: tap, enable: false)
            if let source = runLoopSource {
                CFRunLoopRemoveSource(CFRunLoopGetMain(), source, .commonModes)
            }
            // CFMachPort is managed by the system, invalidate it
            CFMachPortInvalidate(tap)
            eventTap = nil
            runLoopSource = nil
        }
        wordBuffer = ""
        recentTextBuffer = ""
        previousWord = nil
        dismissAutocompletion(hideFieldAnchor: true)
        ServiceStatus.shared.state = .disabled
        NSLog("[LangSwitcher] AutoCorrectionService: stopped")
    }

    @objc private func handleLayoutChanged() {
        wordBuffer = ""
        dismissSuggestionsOnly()
    }

    @objc private func handleAppActivated() {
        dismissSuggestionsOnly()
        aiDebounceTimer.cancel()
        wordBuffer = ""
        recentTextBuffer = ""
        previousWord = nil
        ScreenContextService.shared.invalidateCache()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) { [weak self] in
            self?.updateFieldAnchor()
        }
    }

    @objc private func handleAppDeactivated() {
        dismissAutocompletion(hideFieldAnchor: true)
        stopFieldAnchorPoll()
        ScreenContextService.shared.invalidateCache()
    }

    /// Restart monitoring (e.g., when settings change).
    func restart() {
        stop()
        if settingsManager.needsKeyboardMonitoring {
            start()
        }
    }

    // MARK: - Event Handling (called from C callback on main thread)

    /// Reset word buffer when user clicks with mouse outside the autocompletion popup
    func handleMouseDown() {
        accessibilityService.confirmPendingPasteBeforeInput()
        physicalInputRevision &+= 1
        if overlayController.isVisible && overlayController.containsPoint(NSEvent.mouseLocation) {
            return
        }
        wordBuffer = ""
        recentTextBuffer = ""
        previousWord = nil
        snoozeUntil = nil
        snoozeFieldIdentifier = nil
        dismissSuggestionsOnly()
        aiDebounceTimer.cancel()
        ScreenContextService.shared.invalidateCache()
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) { [weak self] in
            self?.updateFieldAnchor()
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.20) { [weak self] in
            self?.updateFieldAnchor()
        }
    }

    /// Once acceptance consumes a press, repeats and release must not reach the
    /// editor even if the suggestion disappears or its paste is still pending.
    func interceptCompletionKeyEvent(_ event: CGEvent) -> Bool {
        let key = UInt16(event.getIntegerValueField(.keyboardEventKeycode))
        if event.type == .keyUp {
            return consumedAcceptanceKeys.remove(key) != nil
        }
        guard event.type == .keyDown else { return false }
        if consumedAcceptanceKeys.contains(key) {
            if event.getIntegerValueField(.keyboardEventAutorepeat) != 0 { return true }
            // Recover from a missed release while the tap was disabled.
            consumedAcceptanceKeys.remove(key)
        }

        // Intercept keys for auxiliary HUDs (Smart Replies, Word Alternatives, Thesaurus)
        if interceptKeyIfAuxiliaryHUDVisible(event: event) {
            consumedAcceptanceKeys.insert(key)
            return true
        }

        // 0. Immediate undo of last auto-correction via Backspace or Option+Z
        if key == 0x33 && settingsManager.autoCorrectionRevertOnBackspace {
            let noModifiers = event.flags.intersection([.maskCommand, .maskAlternate, .maskControl]).isEmpty
            if noModifiers, let pending = pendingRevertCorrection, Date().timeIntervalSince(pending.timestamp) < 5.0 {
                let context = accessibilityService.captureCaretContext()?.textBeforeCaret ?? recentTextBuffer
                if context.hasSuffix(pending.fullReplacement) || recentTextBuffer.hasSuffix(pending.fullReplacement) || (context.isEmpty && recentTextBuffer.isEmpty) {
                    NSLog("[LangSwitcher] Intercepted Backspace to revert auto-correction '\(pending.replacedWord)' → '\(pending.originalWord)'")
                    _ = revertPendingCorrection()
                    consumedAcceptanceKeys.insert(key)
                    return true
                }
            }
        }

        if key == 0x06 && event.flags.contains(.maskAlternate) && !event.flags.contains(.maskCommand) && !event.flags.contains(.maskControl) {
            let candidate = pendingRevertCorrection ?? (lastAutoCorrection.flatMap { Date().timeIntervalSince($0.timestamp) < 30.0 ? $0 : nil })
            if let targetCorrection = candidate {
                let context = accessibilityService.captureCaretContext()?.textBeforeCaret ?? recentTextBuffer
                if context.hasSuffix(targetCorrection.fullReplacement) || recentTextBuffer.hasSuffix(targetCorrection.fullReplacement) || (context.isEmpty && recentTextBuffer.isEmpty) {
                    NSLog("[LangSwitcher] Intercepted Option+Z to revert auto-correction '\(targetCorrection.replacedWord)' → '\(targetCorrection.originalWord)'")
                    pendingRevertCorrection = targetCorrection
                    _ = revertPendingCorrection()
                    consumedAcceptanceKeys.insert(key)
                    return true
                }
            }
        }

        let isAcceptanceKey = settingsManager.isAutocompletionAcceptKey(keyCode: key, flags: event.flags)
            || settingsManager.isAutocompletionAcceptAllKey(keyCode: key, flags: event.flags)
        let consumed = interceptKeyIfOverlayVisible(event: event)
            || checkGlobalAutocompletionShortcuts(event: event)
        if consumed && isAcceptanceKey { consumedAcceptanceKeys.insert(key) }
        return consumed
    }

    /// Intercept keys for auxiliary HUDs (Smart Replies, Word Alternatives, Thesaurus) synchronously in the CGEvent tap.
    /// Returns true if consumed (tap callback returns nil).
    func interceptKeyIfAuxiliaryHUDVisible(event: CGEvent) -> Bool {
        guard !isProcessingCorrection else { return false }

        let keyCode = UInt16(event.getIntegerValueField(.keyboardEventKeycode))
        let flags = event.flags
        let nonModFlags = flags.intersection([.maskCommand, .maskAlternate, .maskControl])
        let noModifierFlags = flags.intersection([.maskCommand, .maskAlternate, .maskControl, .maskShift])

        let digit: Int? = {
            guard noModifierFlags.isEmpty else { return nil }
            let numberKeyCodes: [UInt16: Int] = [
                0x12: 1, // 1
                0x13: 2, // 2
                0x14: 3, // 3
                0x15: 4, // 4
                0x17: 5, // 5
                0x16: 6, // 6
                0x1A: 7, // 7
                0x1C: 8, // 8
                0x19: 9  // 9
            ]
            if let d = numberKeyCodes[keyCode] { return d }
            if let char = getCharactersFromEvent(event)?.first, let d = Int(String(char)), d >= 1 && d <= 9 {
                return d
            }
            return nil
        }()

        // 1. Smart Replies HUD
        if SmartRepliesController.shared.isVisible {
            if keyCode == 0x35 && nonModFlags.isEmpty { // Escape
                SmartRepliesController.shared.hide()
                return true
            }
            if (keyCode == 0x24 || keyCode == 0x30) && nonModFlags.isEmpty { // Enter or Tab
                if SmartRepliesController.shared.confirmCurrentSelection() {
                    return true
                }
            }
            if (keyCode == 0x7E || keyCode == 0x7B) && nonModFlags.isEmpty { // Up or Left Arrow
                let caret = accessibilityService.caretScreenRect() ?? CGRect(x: 200, y: 500, width: 2, height: 16)
                SmartRepliesController.shared.cyclePrevious(anchor: caret)
                return true
            }
            if (keyCode == 0x7D || keyCode == 0x7C) && nonModFlags.isEmpty { // Down or Right Arrow
                let caret = accessibilityService.caretScreenRect() ?? CGRect(x: 200, y: 500, width: 2, height: 16)
                SmartRepliesController.shared.cycleNext(anchor: caret)
                return true
            }
            if let digit = digit {
                if SmartRepliesController.shared.handleNumericInput(digit) {
                    return true
                }
            }
        }

        // 2. Word Alternatives HUD
        if WordAlternativesController.shared.isVisible {
            if keyCode == 0x35 && nonModFlags.isEmpty { // Escape
                WordAlternativesController.shared.hide()
                return true
            }
            if (keyCode == 0x24 || keyCode == 0x30) && nonModFlags.isEmpty { // Enter or Tab
                if WordAlternativesController.shared.confirmCurrentSelection() {
                    return true
                }
            }
            if (keyCode == 0x7E || keyCode == 0x7B) && nonModFlags.isEmpty { // Up or Left Arrow
                let caret = accessibilityService.caretScreenRect() ?? CGRect(x: 200, y: 500, width: 2, height: 16)
                WordAlternativesController.shared.cyclePrevious(anchor: caret)
                return true
            }
            if (keyCode == 0x7D || keyCode == 0x7C) && nonModFlags.isEmpty { // Down or Right Arrow
                let caret = accessibilityService.caretScreenRect() ?? CGRect(x: 200, y: 500, width: 2, height: 16)
                WordAlternativesController.shared.cycleNext(anchor: caret)
                return true
            }
            if flags.contains(.maskAlternate) && (keyCode == 0x7D || keyCode == 0x7E) { // Option + Down / Up Arrow
                let caret = accessibilityService.caretScreenRect() ?? CGRect(x: 200, y: 500, width: 2, height: 16)
                if keyCode == 0x7D {
                    WordAlternativesController.shared.cycleNext(anchor: caret)
                } else {
                    WordAlternativesController.shared.cyclePrevious(anchor: caret)
                }
                return true
            }
            if let digit = digit {
                if WordAlternativesController.shared.handleNumericInput(digit) {
                    return true
                }
            }
        }

        // Trigger Word Alternatives on Option + Down Arrow when ghost text / autocompletion is active
        if flags.contains(.maskAlternate) && keyCode == 0x7D {
            if triggerWordAlternatives() {
                return true
            }
        }

        // 3. Thesaurus HUD
        if ThesaurusController.shared.isVisible {
            if keyCode == 0x35 && nonModFlags.isEmpty { // Escape
                ThesaurusController.shared.hide()
                return true
            }
            if (keyCode == 0x24 || keyCode == 0x30) && nonModFlags.isEmpty { // Enter or Tab
                if ThesaurusController.shared.confirmFirstCandidate() {
                    return true
                }
            }
            if let digit = digit {
                if ThesaurusController.shared.handleNumericInput(digit) {
                    return true
                }
            }
        }

        return false
    }

    @discardableResult
    func triggerWordAlternatives() -> Bool {
        guard activeGhostState != nil || ghostTextController.isVisible else { return false }
        let caret = accessibilityService.caretScreenRect() ?? CGRect(x: 200, y: 500, width: 2, height: 16)
        let currentWord = ghostTextController.currentCandidate?.word ?? ""
        let activeLayoutID = KeyboardLayoutDetector.getCurrentLayout()?.id ?? "com.apple.keylayout.US"
        let candidates = autocompletionEngine.suggest(
            for: wordBuffer,
            previousWord: previousWord,
            activeLayoutID: activeLayoutID,
            enabledLayouts: settingsManager.enabledLayouts,
            maxSuggestions: 6,
            includeCrossLayout: settingsManager.autoCompletionIncludeCrossLayout,
            allowProfanity: settingsManager.autoCompletionSuggestProfanity,
            bundleID: NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        )
        let alts = WordAlternativesEngine.alternatives(currentSuggestion: currentWord, candidates: candidates.map(\.word))
        guard !alts.isEmpty else { return false }
        WordAlternativesController.shared.show(alternatives: alts, anchor: caret) { [weak self] chosen in
            guard let self else { return }
            let targetLayoutID = self.ghostTextController.currentCandidate?.targetLayoutID ?? activeLayoutID
            let chosenCand = AutocompletionCandidate(word: chosen, targetLayoutID: targetLayoutID)
            self.acceptCandidate(chosenCand, appendSpace: false, entirePhrase: true)
        }
        return true
    }

    /// Check if the key should be intercepted synchronously by the autocompletion overlay.
    /// Returns true if consumed (tap callback returns nil).
    func interceptKeyIfOverlayVisible(event: CGEvent) -> Bool {
        accessibilityService.confirmPendingPasteBeforeInput()
        physicalInputRevision &+= 1
        let isOverlayActive = overlayController.isVisible || ghostTextController.isVisible
            || (phraseContinuationAnchor != nil && (ghostTextController.currentCandidate != nil || !overlayController.candidates.isEmpty))
            || activeGhostState != nil
        guard isOverlayActive else {
            let key = UInt16(event.getIntegerValueField(.keyboardEventKeycode))
            if settingsManager.isAutocompletionAcceptKey(keyCode: key, flags: event.flags)
                || settingsManager.isAutocompletionAcceptAllKey(keyCode: key, flags: event.flags) {
                NSLog("[LangSwitcher] Completion shortcut: no active suggestion")
            }
            return false
        }

        let keyCode = UInt16(event.getIntegerValueField(.keyboardEventKeycode))
        let flags = event.flags
        let isAcceptShortcut = settingsManager.isAutocompletionAcceptKey(keyCode: keyCode, flags: flags)
            || settingsManager.isAutocompletionAcceptAllKey(keyCode: keyCode, flags: flags)
        let isNumberShortcut: Bool = {
            guard settingsManager.autoCompletionUseNumberShortcuts
                && (overlayController.isVisible || (phraseContinuationAnchor != nil && !overlayController.candidates.isEmpty)) else { return false }
            let noMods = flags.intersection([.maskCommand, .maskAlternate, .maskControl, .maskShift]).isEmpty
            guard noMods else { return false }
            return [0x12, 0x13, 0x14, 0x15, 0x17].contains(keyCode)
        }()

        // If a previous completion paste is still awaiting AX confirmation, allow an incoming
        // accept shortcut (e.g. a second consecutive Tab) to finalize the pending paste first
        // instead of failing the isProcessingCorrection guard and leaking Tab to the host app.
        if isProcessingCorrection && (isAcceptShortcut || isNumberShortcut) && accessibilityService.hasPendingPaste {
            accessibilityService.finalizePendingPaste()
        }
        guard !isProcessingCorrection else { return false }
        let nonModFlags = flags.intersection([.maskCommand, .maskAlternate, .maskControl])
        let noModifierFlags = flags.intersection([.maskCommand, .maskAlternate, .maskControl, .maskShift])
        
        // 1. Escape: dismiss overlay & ghost text, snooze suggestions if configured.
        // A subsequent Escape when overlay is hidden passes through to the active application.
        if keyCode == 0x35 && nonModFlags.isEmpty {
            switch settingsManager.autoCompletionEscapeAction {
            case .pauseFewSeconds:
                snoozeUntil = Date().addingTimeInterval(5.0)
                snoozeFieldIdentifier = lastCaretContext?.fieldIdentifier ?? accessibilityService.captureCaretContext()?.fieldIdentifier
            case .dismissOnly:
                break
            }
            dismissAutocompletion(hideFieldAnchor: false)
            return true
        }
        
        // 2. Up Arrow: navigate up in HUD
        if keyCode == 0x7E && nonModFlags.isEmpty && overlayController.isVisible {
            overlayController.selectPrevious()
            return true
        }
        
        // 3. Down Arrow: navigate down in HUD
        if keyCode == 0x7D && nonModFlags.isEmpty && overlayController.isVisible {
            overlayController.selectNext()
            return true
        }
        
        // 4. Number shortcuts 1-5 (if enabled, requiring no Shift/Cmd/Opt/Ctrl so !@#$% are not caught)
        if settingsManager.autoCompletionUseNumberShortcuts && noModifierFlags.isEmpty && overlayController.isVisible {
            let numberKeyCodes: [UInt16: Int] = [
                0x12: 0, // 1
                0x13: 1, // 2
                0x14: 2, // 3
                0x15: 3, // 4
                0x17: 4  // 5
            ]
            if let index = numberKeyCodes[keyCode], index < overlayController.candidates.count {
                let candidate = overlayController.candidates[index]
                return submitCandidate(candidate, appendSpace: false, entirePhrase: true, failureEvent: event)
            }
        }
        
        // 5. Configured Accept ALL Key (e.g. ⌘§, Shift+Tab, Option+Tab, Cmd+Return)
        if settingsManager.isAutocompletionAcceptAllKey(keyCode: keyCode, flags: flags) {
            let candidate = overlayController.selectedCandidate
                ?? overlayController.candidates.first
                ?? ghostTextController.currentCandidate
                ?? (activeGhostState.map { state in
                    AutocompletionCandidate(
                        word: wordBuffer.isEmpty ? state.remainingSuffix : (wordBuffer + state.remainingSuffix),
                        targetLayoutID: KeyboardLayoutDetector.getCurrentLayout()?.id ?? "com.apple.keylayout.US",
                        isCrossLayout: false,
                        score: 1500
                    )
                })
            if let candidate = candidate {
                return submitCandidate(candidate, appendSpace: false, entirePhrase: true, failureEvent: event)
            }
        }

        // 6. Configured Accept next word / entire phrase Key (e.g. Tab, Space, Enter, Right Arrow)
        if settingsManager.isAutocompletionAcceptKey(keyCode: keyCode, flags: flags) {
            let candidate = overlayController.selectedCandidate
                ?? overlayController.candidates.first
                ?? ghostTextController.currentCandidate
                ?? (activeGhostState.map { state in
                    AutocompletionCandidate(
                        word: wordBuffer.isEmpty ? state.remainingSuffix : (wordBuffer + state.remainingSuffix),
                        targetLayoutID: KeyboardLayoutDetector.getCurrentLayout()?.id ?? "com.apple.keylayout.US",
                        isCrossLayout: false,
                        score: 1500
                    )
                })
            if let candidate = candidate {
                let entirePhrase = settingsManager.autoCompletionAcceptEntirePhrase
                let appendSpace = settingsManager.autoCompletionIncludeTrailingSpace || (settingsManager.autoCompletionAcceptKey == .space)
                return submitCandidate(candidate, appendSpace: appendSpace, entirePhrase: entirePhrase, failureEvent: event)
            }
        }
        
        // Check for Type-Ahead if ghost text is active
        if activeGhostState != nil,
           nonModFlags.isEmpty,
           let char = getCharactersFromEvent(event)?.first {
            if handleTypeAhead(char: char) {
                // Key matched type-ahead. Let it pass through to the editor.
                typeAheadHandledCount += 1
                return false
            }
        }
        
        // Invalidate candidates before any other physical key reaches the editor.
        dismissSuggestionsOnly()
        return false
    }

    /// Synchronously processes a matching character during active ghost text,
    /// trimming the remaining suffix and updating the insertion target.
    @discardableResult
    func handleTypeAhead(char: Character) -> Bool {
        guard var state = activeGhostState else { return false }
        guard let firstChar = state.remainingSuffix.first else {
            activeGhostState = nil
            ghostTextController.hide()
            overlayController.hide()
            Task { await AILocalEngine.shared.resetStitch() }
            return false
        }

        // Support leading space in suggestion: if suggestion starts with " " and user types next word character directly,
        // advance past the space and match the character.
        if firstChar == " " && char != " " {
            state.remainingSuffix.removeFirst()
            guard let nextChar = state.remainingSuffix.first,
                  (nextChar == char || nextChar.lowercased() == char.lowercased()) else {
                activeGhostState = nil
                ghostTextController.hide()
                overlayController.hide()
                dismissSuggestionsOnly()
                scheduleAIDebounce()
                Task { await AILocalEngine.shared.resetStitch() }
                return false
            }
        } else {
            let matches = firstChar == char || firstChar.lowercased() == char.lowercased()
            guard matches else {
                activeGhostState = nil
                ghostTextController.hide()
                overlayController.hide()
                dismissSuggestionsOnly()
                scheduleAIDebounce()
                Task { await AILocalEngine.shared.resetStitch() }
                return false
            }
        }

        // MATCH:
        state.remainingSuffix.removeFirst()

        // Advance native Metal engine stitch session in background
        Task {
            _ = await AILocalEngine.shared.attemptStitch(typedText: String(char))
        }

        let isBoundary = char.isWhitespace || (!char.isLetter && !char.isNumber && !isAlternativeLetterKey(char))
        if isBoundary {
            let previous = (previousWord ?? "")
            previousWord = previous.isEmpty ? wordBuffer : (previous + " " + wordBuffer).trimmingCharacters(in: .whitespaces)
            wordBuffer = ""
        } else {
            wordBuffer.append(char)
        }

        if state.suggestionTarget == nil {
            let updatedTarget = accessibilityService.captureReplacementTarget()
            state.suggestionTarget = updatedTarget
            self.suggestionTarget = updatedTarget
        }

        if state.remainingSuffix.isEmpty {
            activeGhostState = nil
            ghostTextController.hide()
            overlayController.hide()
            dismissSuggestionsOnly()
            scheduleAIDebounce()
            Task { await AILocalEngine.shared.resetStitch() }
            return true
        }

        self.activeGhostState = state

        let activeLayoutID = KeyboardLayoutDetector.getCurrentLayout()?.id ?? "com.apple.keylayout.US"
        let fullWord = wordBuffer.isEmpty ? state.remainingSuffix : (wordBuffer + state.remainingSuffix)
        let updatedCandidate = AutocompletionCandidate(
            word: fullWord,
            targetLayoutID: activeLayoutID,
            isCrossLayout: false,
            score: 1500,
            hasScreenContext: ghostTextController.currentCandidate?.hasScreenContext ?? false
        )

        let isOverlayDisplayed = ghostTextController.isVisible
        let bounds = isOverlayDisplayed ? nil : accessibilityService.caretAndFieldBounds()
        let currentCaret = bounds?.caret ?? ghostTextController.lastCaretRect ?? state.caretRect
        state.caretRect = currentCaret
        self.activeGhostState = state

        let displayMode = settingsManager.autoCompletionDisplayMode
        if displayMode == .ghostText || displayMode == .both {
            ghostTextController.show(
                candidate: updatedCandidate,
                suffix: state.remainingSuffix,
                caretRect: currentCaret,
                fieldRect: bounds?.fieldRect ?? ghostTextController.lastFieldRect,
                caretProvider: { [weak self] in self?.accessibilityService.caretScreenRect() }
            )
        }

        if (displayMode == .popup || displayMode == .both) && overlayController.isVisible {
            let hint = settingsManager.autoCompletionAcceptKey.shortcutHint(
                customKeyCode: settingsManager.autoCompletionCustomKeyCode,
                customModifiers: settingsManager.autoCompletionCustomModifiers
            )
            overlayController.show(
                candidates: [updatedCandidate],
                caretRect: currentCaret,
                acceptKeyHint: hint,
                caretProvider: { [weak self] in self?.accessibilityService.caretScreenRect() },
                onSelect: { [weak self] candidate in
                    self?.acceptCandidate(candidate, appendSpace: false, entirePhrase: true)
                }
            )
        }

        let wordCount = state.remainingSuffix.split(separator: " ").count
        if wordCount <= 2 {
            scheduleAIDebounce()
        }

        return true
    }

    private func submitCandidate(_ candidate: AutocompletionCandidate, appendSpace: Bool,
                                 entirePhrase: Bool, failureEvent: CGEvent) -> Bool {
        if let acceptanceHandler {
            return acceptanceHandler(candidate, appendSpace, entirePhrase, failureEvent)
        }
        return acceptCandidate(candidate, appendSpace: appendSpace, entirePhrase: entirePhrase, failureEvent: failureEvent)
    }

    private var completionsEnabledForCurrentApp: Bool {
        settingsManager.autoCompletionEnabled && !completionPauses.isPaused(
            bundleID: NSWorkspace.shared.frontmostApplication?.bundleIdentifier, now: Date())
    }

    /// Check if the key matches a global autocompletion shortcut when overlay is not visible.
    func checkGlobalAutocompletionShortcuts(event: CGEvent) -> Bool {
        // Let the settings window's recorder receive its own shortcuts.
        guard !isProcessingCorrection, !NSApp.isActive else { return false }
        let keyCode = UInt16(event.getIntegerValueField(.keyboardEventKeycode))
        let flags = event.flags
        
        if settingsManager.isAutocompletionForceActivateKey(keyCode: keyCode, flags: flags) {
            forceActivateCompletion()
            return true
        }
        if settingsManager.isAutocompletionToggleCurrentAppKey(keyCode: keyCode, flags: flags) {
            toggleCompletionsForCurrentApp()
            return true
        }
        if settingsManager.isAutocompletionToggleGlobalKey(keyCode: keyCode, flags: flags) {
            toggleCompletionsGlobally()
            return true
        }
        return false
    }

    /// Manually trigger suggestions at current cursor position
    func forceActivateCompletion() {
        guard completionsEnabledForCurrentApp,
              let context = accessibilityService.captureCaretContext(maxSurroundingLength: 2048),
              context.hasUsablePredictionContext else { return }
        snoozeUntil = nil
        snoozeFieldIdentifier = nil
        let input = CompletionTypingContext(beforeCaret: context.textBeforeCaret)
        wordBuffer = input.prefix
        previousWord = input.previousWord
        dismissSuggestionsOnly()
        if !wordBuffer.isEmpty { updateAutocompletion(force: true) }
        scheduleAIDebounce(force: true)
    }

    /// Pause only completions for five minutes; leave permanent correction exclusions intact.
    func toggleCompletionsForCurrentApp() {
        guard let bundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier else { return }
        if completionPauses.toggle(bundleID: bundleID, now: Date()) {
            dismissAutocompletion(hideFieldAnchor: true)
        }
        playCorrectionFeedback()
    }

    /// Toggle completions globally across the entire system
    func toggleCompletionsGlobally() {
        settingsManager.autoCompletionEnabled.toggle()
        if !settingsManager.autoCompletionEnabled {
            dismissAutocompletion()
        }
        playCorrectionFeedback()
    }

    /// Process a keyDown event. Dispatches to MainActor via DispatchQueue.main.async to guarantee FIFO order.
    nonisolated func handleKeyEvent(_ event: CGEvent) {
        let keyCode = event.getIntegerValueField(.keyboardEventKeycode)
        let flags = event.flags
        let characters = getCharactersFromEvent(event)

        DispatchQueue.main.async { [weak self] in
            self?.processKey(keyCode: UInt16(keyCode), flags: flags, characters: characters)
        }
    }

    // MARK: - Key Processing

    private func processKey(keyCode: UInt16, flags: CGEventFlags, characters: String?) {
        guard settingsManager.autoCorrectionEnabled || settingsManager.autoCompletionEnabled else { return }
        guard !settingsManager.isTemporarilyPaused else { return }

        // Ignore events with Command or Control modifier (⌘C, ⌘V, ⌃Space layout switch, etc.)
        if flags.contains(.maskCommand) || flags.contains(.maskControl) {
            wordBuffer = ""
            overlayController.hide()
            ghostTextController.hide()
            activeGhostState = nil
            currentAIRequestId = nil
            typeAheadHandledCount = 0
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) { [weak self] in
                self?.updateFieldAnchor()
            }
            return
        }

        // Any key that reaches processKey is not an intercepted undo, so invalidate immediate undo.
        pendingRevertCorrection = nil

        if typeAheadHandledCount > 0 {
            typeAheadHandledCount -= 1
            if let char = characters?.first {
                recentTextBuffer.append(char)
                if recentTextBuffer.count > 250 { recentTextBuffer.removeFirst(recentTextBuffer.count - 250) }
            }
            scheduleFieldAnchorDebounce()
            return
        }

        // Dismiss auxiliary HUDs if normal typing continues
        if SmartRepliesController.shared.isVisible {
            SmartRepliesController.shared.hide()
        }
        if WordAlternativesController.shared.isVisible {
            WordAlternativesController.shared.hide()
        }
        if ThesaurusController.shared.isVisible {
            ThesaurusController.shared.hide()
        }

        // Handle special keys
        switch keyCode {
        case 0x33: // Backspace
            if flags.contains(.maskAlternate) {
                wordBuffer = ""
                recentTextBuffer = ""
            } else if !wordBuffer.isEmpty {
                wordBuffer.removeLast()
            }
            if !recentTextBuffer.isEmpty {
                recentTextBuffer.removeLast()
            }
            scheduleAutocompletion()
            return

        case 0x7B, 0x7C, 0x7D, 0x7E: // Arrow keys (left, right, down, up)
            wordBuffer = ""
            recentTextBuffer = ""
            previousWord = nil
            dismissSuggestionsOnly()
            aiDebounceTimer.cancel()
            return

        case 0x35: // Escape
            wordBuffer = ""
            recentTextBuffer = ""
            previousWord = nil
            dismissSuggestionsOnly()
            aiDebounceTimer.cancel()
            updateFieldAnchor()
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.15) { [weak self] in
                self?.updateFieldAnchor()
            }
            return

        case 0x30: // Tab
            wordBuffer = ""
            recentTextBuffer = ""
            dismissSuggestionsOnly()
            aiDebounceTimer.cancel()
            return

        case 0x24, 0x4C: // Return/Enter or Keypad Enter
            recordHistorySnippetIfEligible()
            if !wordBuffer.isEmpty {
                previousWord = wordBuffer.lowercased()
            }
            wordBuffer = ""
            recentTextBuffer.append("\n")
            if recentTextBuffer.count > 250 { recentTextBuffer.removeFirst(recentTextBuffer.count - 250) }
            dismissSuggestionsOnly()
            aiDebounceTimer.cancel()
            return

        case 0x31: // Space
            dismissSuggestionsOnly()
            if settingsManager.autoCorrectionEnabled && settingsManager.autoCorrectionEmojiShortcodes {
                let context = (accessibilityService.captureCaretContext()?.textBeforeCaret ?? recentTextBuffer) + " "
                if let emojiMatch = EmojiShortcodeEngine.findSpaceReplacement(in: context) {
                    performCheckedReplacement(expected: emojiMatch.expected, replacement: emojiMatch.replacement) { [weak self] _ in
                        guard let self else { return }
                        self.playCorrectionFeedback()
                        self.settingsManager.recordAutoCorrection(charCount: emojiMatch.expected.count)
                    }
                    wordBuffer = ""
                    recentTextBuffer.append(" ")
                    if recentTextBuffer.count > 250 { recentTextBuffer.removeFirst(recentTextBuffer.count - 250) }
                    scheduleAIDebounce()
                    return
                }
            }
            if settingsManager.autoCorrectionEnabled {
                triggerCheckAndCorrect(triggerChar: " ")
            } else {
                if !wordBuffer.isEmpty {
                    previousWord = wordBuffer.lowercased()
                }
                wordBuffer = ""
            }
            recentTextBuffer.append(" ")
            if recentTextBuffer.count > 250 { recentTextBuffer.removeFirst(recentTextBuffer.count - 250) }
            scheduleAIDebounce()
            return

        default:
            break
        }

        // Get the typed character
        guard let chars = characters, !chars.isEmpty else { return }

        let char = chars.first!

        // If an active ghost completion is visible, check if typing this character advances it
        if activeGhostState != nil && handleTypeAhead(char: char) {
            recentTextBuffer.append(char)
            if recentTextBuffer.count > 250 { recentTextBuffer.removeFirst(recentTextBuffer.count - 250) }
            scheduleFieldAnchorDebounce()
            return
        }

        // Check for emoji shortcode closed with colon (e.g. ":fire:" or ":огонь:" -> 🔥)
        if char == ":" && settingsManager.autoCorrectionEnabled && settingsManager.autoCorrectionEmojiShortcodes {
            let context = (accessibilityService.captureCaretContext()?.textBeforeCaret ?? recentTextBuffer) + ":"
            if let emojiMatch = EmojiShortcodeEngine.findColonReplacement(in: context) {
                performCheckedReplacement(expected: emojiMatch.expected, replacement: emojiMatch.replacement) { [weak self] _ in
                    guard let self else { return }
                    self.playCorrectionFeedback()
                    self.settingsManager.recordAutoCorrection(charCount: emojiMatch.expected.count)
                }
                wordBuffer = ""
                recentTextBuffer.append(char)
                if recentTextBuffer.count > 250 { recentTextBuffer.removeFirst(recentTextBuffer.count - 250) }
                return
            }
        }

        // Check for typographic smart dashes & ellipsis
        if settingsManager.autoCorrectionEnabled && settingsManager.autoCorrectionSmartDashesAndEllipsis {
            let context = accessibilityService.captureCaretContext()?.textBeforeCaret ?? recentTextBuffer
            if let typo = SmartPunctuationEngine.smartDashesAndEllipsis(char: char, precedingText: context) {
                performCheckedReplacement(expected: typo.expected, replacement: typo.replacement) { [weak self] _ in
                    guard let self else { return }
                    self.playCorrectionFeedback()
                    self.settingsManager.recordAutoCorrection(charCount: typo.expected.count)
                }
                recentTextBuffer.append(char)
                if recentTextBuffer.count > 250 { recentTextBuffer.removeFirst(recentTextBuffer.count - 250) }
                return
            }
        }

        // Check for accidental space before punctuation (e.g. "слово ," -> "слово,")
        if settingsManager.autoCorrectionEnabled && settingsManager.autoCorrectionRemoveSpaceBeforePunctuation {
            let context = accessibilityService.captureCaretContext()?.textBeforeCaret ?? recentTextBuffer
            if let fix = SmartPunctuationEngine.fixSpaceBeforePunctuation(char: char, precedingText: context) {
                performCheckedReplacement(expected: fix.expected, replacement: fix.replacement) { [weak self] _ in
                    guard let self else { return }
                    self.playCorrectionFeedback()
                    self.settingsManager.recordAutoCorrection(charCount: 1)
                }
                if recentTextBuffer.hasSuffix(" ") {
                    recentTextBuffer.removeLast()
                }
                recentTextBuffer.append(char)
                if recentTextBuffer.count > 250 { recentTextBuffer.removeFirst(recentTextBuffer.count - 250) }
                dismissSuggestionsOnly()
                scheduleAIDebounce()
                return
            }
        }

        // Check if it's a word boundary (punctuation)
        if !char.isLetter && !char.isNumber && !isAlternativeLetterKey(char) {
            dismissSuggestionsOnly()
            if settingsManager.autoCorrectionEnabled {
                triggerCheckAndCorrect(triggerChar: char)
            } else {
                if !wordBuffer.isEmpty {
                    previousWord = wordBuffer.lowercased()
                }
                wordBuffer = ""
            }
            recentTextBuffer.append(char)
            if recentTextBuffer.count > 250 { recentTextBuffer.removeFirst(recentTextBuffer.count - 250) }
            scheduleAIDebounce()
            return
        }

        // Accumulate character in word buffer and recent text buffer
        wordBuffer.append(char)
        recentTextBuffer.append(char)
        if recentTextBuffer.count > 250 { recentTextBuffer.removeFirst(recentTextBuffer.count - 250) }
        scheduleAutocompletion()
    }

    private func isAlternativeLetterKey(_ char: Character) -> Bool {
        let targets = settingsManager.enabledLayouts.map(\.id)
        let source = KeyboardLayoutDetector.getCurrentLayout()?.id ?? targets.first ?? "com.apple.keylayout.US"
        return CorrectionToken.isAlternativeLetter(char, source: source, targets: targets)
    }

    // MARK: - Autocompletion Logic

    /// Dismiss current suggestion popup and ghost text without resetting AI debounce or hiding the field anchor.
    func dismissSuggestionsOnly() {
        if let current = currentAIRequestId {
            if cancelledRequestIds.count > 100 {
                cancelledRequestIds.removeAll(keepingCapacity: true)
            }
            cancelledRequestIds.insert(current)
        }
        activeGhostState = nil
        currentAIRequestId = nil
        completionRefresh.cancel()
        suggestionTarget = nil
        phraseContinuationAnchor = nil
        lastCaretContext = nil
        overlayController.hide()
        ghostTextController.hide()
        WordAlternativesController.shared.hide()
        ThesaurusController.shared.hide()
        SmartRepliesController.shared.hide()
        fieldAnchorController.updateContextState(hasScreenContext: false, hasPendingQuestion: false)
        Task { await AILocalEngine.shared.resetStitch() }
    }

    /// Full dismissal called on Escape, App switch, or deactivation.
    private func dismissAutocompletion(hideFieldAnchor: Bool = false) {
        if let current = currentAIRequestId {
            cancelledRequestIds.insert(current)
        }
        dismissSuggestionsOnly()
        aiDebounceTimer.cancel()
        ScreenContextService.shared.invalidateCache()
        if hideFieldAnchor {
            fieldAnchorDebounce.cancel()
            fieldAnchorController.hide()
            stopFieldAnchorPoll()
        }
    }

    private func startFieldAnchorPoll() {
        // Continuous polling via Timer causes Mach IPC stalls and deadlocks in WindowServer.
        // Anchor positions are refreshed reactively on typing and app focus events instead.
    }

    private func stopFieldAnchorPoll() {
        // No-op
    }

    private func scheduleFieldAnchorDebounce() {
        fieldAnchorDebounce.schedule(delay: 0.500) { [weak self] in
            self?.updateFieldAnchor()
        }
    }

    private func scheduleAutocompletion() {
        completionRefresh.cancel()
        scheduleFieldAnchorDebounce()
        // Measure after the editor receives the physical key, coalescing fast typing.
        let delay = settingsManager.autoCompletionDelay
        completionRefresh.schedule(delay: delay) { [weak self] in
            self?.updateAutocompletion()
        }
        scheduleAIDebounce()
    }

    private func updateFieldAnchor() {
        guard settingsManager.showFieldAnchorBadge, completionsEnabledForCurrentApp, !NSApp.isActive else {
            fieldAnchorController.hide()
            stopFieldAnchorPoll()
            return
        }
        let focus = accessibilityService.focusedFieldRole()
        let frontmostBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        guard AutoCorrectionGate.allowsAutoCorrection(
            role: focus?.role,
            subrole: focus?.subrole,
            bundleID: frontmostBundleID,
            excludedBundleIDs: Set(settingsManager.excludedAppBundleIDs)
        ) else {
            fieldAnchorController.hide()
            stopFieldAnchorPoll()
            return
        }
        if let fieldRect = accessibilityService.focusedFieldScreenRect() {
            fieldAnchorController.show(fieldRect: fieldRect)
            startFieldAnchorPoll()
        } else {
            fieldAnchorController.hide()
            stopFieldAnchorPoll()
        }
    }

    private func recordHistorySnippetIfEligible() {
        guard settingsManager.aiPersonalizationEnabled else { return }
        guard !NSApp.isActive else { return }
        let focus = accessibilityService.focusedFieldRole()
        let currentBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier ?? "unknown"
        guard AutoCorrectionGate.allowsAutoCorrection(
            role: focus?.role,
            subrole: focus?.subrole,
            bundleID: currentBundleID,
            excludedBundleIDs: Set(settingsManager.excludedAppBundleIDs)
        ) else { return }
        guard settingsManager.isAIEnabled(for: currentBundleID) else { return }
        
        guard let caretContext = accessibilityService.captureCaretContext(maxSurroundingLength: 1024),
              caretContext.hasUsablePredictionContext else { return }
        
        let text = caretContext.textBeforeCaret
        let lastLine = text.components(separatedBy: .newlines).last ?? text
        guard !AutoCorrectionGate.containsSensitiveInformation(lastLine) else { return }
        UserTextHistoryStore.shared.recordSnippet(text: lastLine, bundleID: currentBundleID)
    }

    private func scheduleAIDebounce(force: Bool = false) {
        aiDebounceTimer.cancel()
        guard settingsManager.isAIAllowed, completionsEnabledForCurrentApp, Date() >= (snoozeUntil ?? .distantPast) else { return }
        guard AIModelManager.shared.state.isReady else { return }
        guard !NSApp.isActive else { return }

        let captureRevision = physicalInputRevision
        let activeLayoutID = KeyboardLayoutDetector.getCurrentLayout()?.id ?? "com.apple.keylayout.US"
        let frontmostBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        guard settingsManager.isAIEnabled(for: frontmostBundleID) else { return }
        let instructions = settingsManager.aiInstructions(for: frontmostBundleID)
        let maxWords = settingsManager.aiMaxContinuationWords

        let effectiveDelay = force ? 0 : BatteryPowerManager.shared.effectiveDebounceDelay(baseDelay: settingsManager.aiDebounceDelay)
        aiDebounceTimer.schedule(delay: effectiveDelay) { [weak self] in
            guard let self = self else { return }
            guard self.physicalInputRevision == captureRevision else { return }
            guard self.settingsManager.isAIAllowed else { return }

            // No one-word fallback: it invents a topic when AX context is unavailable.
            guard self.completionsEnabledForCurrentApp, Date() >= (self.snoozeUntil ?? .distantPast),
                  let caretContext = self.accessibilityService.captureCaretContext(maxSurroundingLength: 2048),
                  caretContext.hasUsablePredictionContext else { return }
            let focus = self.accessibilityService.focusedFieldRole()
            let currentBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
            guard AutoCorrectionGate.allowsAutoCorrection(role: focus?.role, subrole: focus?.subrole,
                bundleID: currentBundleID,
                excludedBundleIDs: Set(self.settingsManager.excludedAppBundleIDs)) else { return }
            guard self.settingsManager.isAIEnabled(for: currentBundleID) else { return }

            let requestId = UUID()
            self.currentAIRequestId = requestId
            let fieldID = caretContext.fieldIdentifier
            let initialBuffer = self.wordBuffer
            let initialCaret = self.accessibilityService.caretScreenRect() ?? .zero

            let liveContext = caretContext.textBeforeCaret
            let currentLang = AIInferenceEngine.containsCyrillic(liveContext) ? "ru" : "en"
            let currentInstructions = self.settingsManager.aiInstructions(for: currentBundleID, language: currentLang)

            var screenContextText: String?
            var hasPendingQuestion = false
            var webDomain: String?
            if self.settingsManager.aiScreenContextEnabled {
                if let screenCtx = await ScreenContextService.shared.extractScreenContextAsync(
                    frontmostApp: NSWorkspace.shared.frontmostApplication,
                    focusedElement: self.accessibilityService.focusedTextElement(),
                    excludedBundleIDs: Set(self.settingsManager.excludedAppBundleIDs)
                ) {
                    screenContextText = screenCtx.formattedContext
                    hasPendingQuestion = screenCtx.hasPendingQuestion
                    webDomain = screenCtx.webDomain
                }
            }
            if webDomain == nil, let app = NSWorkspace.shared.frontmostApplication,
               BrowserDomainExtractor.isBrowser(bundleID: app.bundleIdentifier) {
                webDomain = BrowserDomainExtractor.shared.extractDomain(
                    pid: app.processIdentifier,
                    bundleID: app.bundleIdentifier ?? "",
                    focusedElement: self.accessibilityService.focusedTextElement()
                )
            }

            guard self.currentAIRequestId == requestId else { return }

            self.fieldAnchorController.updateContextState(
                hasScreenContext: screenContextText != nil,
                hasPendingQuestion: hasPendingQuestion
            )

            var effectiveMaxWords = maxWords
            let contextWordCount = liveContext.trimmingCharacters(in: .whitespacesAndNewlines).split(separator: " ").count
            if screenContextText == nil && contextWordCount <= 1 {
                // When there is zero dialogue context and the user has only typed a single word,
                // keep continuation conservative to prevent ungrounded topic invention.
                effectiveMaxWords = min(maxWords, self.wordBuffer.isEmpty ? 1 : 2)
            }

            let hasContext = screenContextText != nil
            let windowInfo = self.accessibilityService.activeWindowContext()
            let appName = windowInfo.appName
            let windowTitle = windowInfo.windowTitle

            let allowProfanity = self.settingsManager.autoCompletionSuggestProfanity

            if self.settingsManager.aiStreamingEnabled {
                let streamResult = await AIInferenceEngine.shared.predictContinuationStream(
                    context: liveContext,
                    afterCaret: String(caretContext.textAfterCaret.prefix(512)),
                    wordBuffer: self.wordBuffer,
                    maxWords: effectiveMaxWords,
                    customInstructions: currentInstructions,
                    screenContext: screenContextText,
                    hasPendingQuestion: hasPendingQuestion,
                    appName: appName,
                    windowTitle: windowTitle,
                    webDomain: webDomain,
                    allowProfanity: allowProfanity
                ) { [weak self] partialSuffix in
                    guard let self else { return }
                    guard self.currentAIRequestId == requestId else { return }
                    guard self.completionsEnabledForCurrentApp else { return }
                    if !allowProfanity && ProfanityFilter.isProfane(partialSuffix) {
                        self.dismissSuggestionsOnly()
                        return
                    }

                    // Word boundary check: only update streaming ghost text
                    // when a full word boundary is formed (space, punctuation, or newline)
                    let hasWordBoundary = partialSuffix.last?.isWhitespace == true ||
                                          partialSuffix.last?.isPunctuation == true ||
                                          partialSuffix.last?.isNewline == true
                    guard hasWordBoundary else { return }

                    // Validate field identity and text context before presenting
                    guard self.accessibilityService.focusedFieldIdentifier() == fieldID,
                          let currentContext = self.accessibilityService.captureCaretContext(maxSurroundingLength: 512),
                          currentContext.fieldIdentifier == fieldID,
                          initialBuffer.isEmpty || currentContext.textBeforeCaret.hasSuffix(initialBuffer) else {
                        self.dismissSuggestionsOnly()
                        return
                    }

                    self.presentAIPrediction(
                        suffix: partialSuffix,
                        activeLayoutID: activeLayoutID,
                        hasScreenContext: hasContext,
                        requestId: requestId,
                        fieldIdentifier: fieldID,
                        initialBuffer: initialBuffer,
                        caretRect: initialCaret,
                        isFinal: false
                    )
                }
                if let finalSuffix = streamResult {
                    guard self.currentAIRequestId == requestId else { return }
                    guard self.completionsEnabledForCurrentApp else { return }
                    if !allowProfanity && ProfanityFilter.isProfane(finalSuffix) {
                        self.dismissSuggestionsOnly()
                        return
                    }
                    guard self.accessibilityService.focusedFieldIdentifier() == fieldID,
                          let currentContext = self.accessibilityService.captureCaretContext(maxSurroundingLength: 512),
                          currentContext.fieldIdentifier == fieldID,
                          initialBuffer.isEmpty || currentContext.textBeforeCaret.hasSuffix(initialBuffer) else {
                        self.dismissSuggestionsOnly()
                        return
                    }
                    self.presentAIPrediction(
                        suffix: finalSuffix,
                        activeLayoutID: activeLayoutID,
                        hasScreenContext: hasContext,
                        requestId: requestId,
                        fieldIdentifier: fieldID,
                        initialBuffer: initialBuffer,
                        caretRect: initialCaret,
                        isFinal: true
                    )
                } else {
                    // Stale / cancelled / failed stream requests must not dismiss or overwrite an active valid suggestion.
                    guard self.currentAIRequestId == requestId else { return }
                    if self.accessibilityService.focusedFieldIdentifier() != fieldID {
                        self.dismissSuggestionsOnly()
                    }
                }
            } else {
                guard let suffix = await AIInferenceEngine.shared.predictContinuation(
                    context: liveContext,
                    afterCaret: String(caretContext.textAfterCaret.prefix(512)),
                    wordBuffer: self.wordBuffer,
                    maxWords: effectiveMaxWords,
                    customInstructions: currentInstructions,
                    screenContext: screenContextText,
                    hasPendingQuestion: hasPendingQuestion,
                    appName: appName,
                    windowTitle: windowTitle,
                    webDomain: webDomain,
                    allowProfanity: allowProfanity
                ) else {
                    guard self.currentAIRequestId == requestId else { return }
                    if self.accessibilityService.focusedFieldIdentifier() != fieldID {
                        self.dismissSuggestionsOnly()
                    }
                    return
                }
                guard self.currentAIRequestId == requestId else { return }
                guard self.completionsEnabledForCurrentApp else { return }
                if !allowProfanity && ProfanityFilter.isProfane(suffix) {
                    self.dismissSuggestionsOnly()
                    return
                }
                guard self.accessibilityService.focusedFieldIdentifier() == fieldID,
                      let currentContext = self.accessibilityService.captureCaretContext(maxSurroundingLength: 512),
                      currentContext.fieldIdentifier == fieldID,
                      initialBuffer.isEmpty || currentContext.textBeforeCaret.hasSuffix(initialBuffer) else {
                    self.dismissSuggestionsOnly()
                    return
                }

                self.presentAIPrediction(
                    suffix: suffix,
                    activeLayoutID: activeLayoutID,
                    hasScreenContext: hasContext,
                    requestId: requestId,
                    fieldIdentifier: fieldID,
                    initialBuffer: initialBuffer,
                    caretRect: initialCaret,
                    isFinal: true
                )
            }
        }
    }

    func presentAIPrediction(
        suffix: String,
        activeLayoutID: String,
        hasScreenContext: Bool = false,
        requestId: UUID? = nil,
        fieldIdentifier: String? = nil,
        initialBuffer: String? = nil,
        caretRect: CGRect? = nil,
        isFinal: Bool = false
    ) {
        guard !suffix.isEmpty else { return }
        let effectiveRequestId = requestId ?? currentAIRequestId ?? UUID()
        if let reqId = requestId {
            if cancelledRequestIds.contains(reqId) {
                return
            }
            if let current = currentAIRequestId, current != reqId {
                return
            }
        }

        let displayMode = settingsManager.autoCompletionDisplayMode

        // Check focus & gate if focused element is present
        if let role = accessibilityService.focusedFieldRole()?.role {
            let frontmostBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
            guard AutoCorrectionGate.allowsAutoCorrection(
                role: role,
                subrole: accessibilityService.focusedFieldRole()?.subrole,
                bundleID: frontmostBundleID,
                excludedBundleIDs: Set(settingsManager.excludedAppBundleIDs)
            ) else { return }
        }

        // Determine whether the caret currently has preceding whitespace.
        // If typing directly against a word boundary (e.g. "Как|"), the suggestion
        // must include a leading space so it does not glue to the caret or word.
        let ctx = self.accessibilityService.captureCaretContext(maxSurroundingLength: 256) ?? self.lastCaretContext
        let textBefore = ctx?.textBeforeCaret ?? ""
        let hasPrecedingSpace = textBefore.isEmpty || textBefore.last?.isWhitespace == true

        var displaySuffix: String
        let trimmedLeading = suffix.trimmingCharacters(in: .whitespaces)
        if hasPrecedingSpace {
            displaySuffix = trimmedLeading
        } else if wordBuffer.isEmpty {
            if let firstChar = trimmedLeading.first, firstChar.isLetter || firstChar.isNumber || firstChar.isSymbol {
                displaySuffix = " " + trimmedLeading
            } else {
                displaySuffix = suffix
            }
        } else {
            if suffix.hasPrefix(" ") && !trimmedLeading.isEmpty {
                displaySuffix = " " + trimmedLeading
            } else {
                displaySuffix = suffix
            }
        }
        let fullPhrase = wordBuffer.isEmpty ? displaySuffix : (wordBuffer + displaySuffix)

        guard !displaySuffix.isEmpty else { return }

        if !settingsManager.autoCompletionSuggestProfanity {
            if ProfanityFilter.isProfane(displaySuffix) || ProfanityFilter.isProfane(fullPhrase) {
                return
            }
        }

        // Prefix Invariance Enforcement:
        // Updates are only permitted if newCandidate extends alreadyVisibleText
        var effectiveRemainingSuffix = displaySuffix
        if let existing = self.activeGhostState {
            let alreadyVisibleText = existing.remainingSuffix
            let fullPrior = existing.fullCompletionText
            var candidateToCheck = displaySuffix

            let normalizedVisible = alreadyVisibleText.trimmingCharacters(in: .whitespaces)
            let normalizedCandidate = candidateToCheck.trimmingCharacters(in: .whitespaces)

            if existing.requestId == effectiveRequestId {
                let isPrefixValid = candidateToCheck.hasPrefix(alreadyVisibleText) ||
                                   (candidateToCheck.hasPrefix(fullPrior) && fullPrior.hasSuffix(alreadyVisibleText)) ||
                                   (!normalizedVisible.isEmpty && normalizedCandidate.hasPrefix(normalizedVisible))

                if !isPrefixValid {
                    NSLog("[LangSwitcher] Prefix invariance: discarded divergence (new='%@', visible='%@')", displaySuffix, alreadyVisibleText)
                    return
                }

                let typedCount = fullPrior.count - alreadyVisibleText.count
                if typedCount > 0 && candidateToCheck.hasPrefix(fullPrior) && candidateToCheck.count >= typedCount {
                    effectiveRemainingSuffix = String(candidateToCheck.dropFirst(typedCount))
                } else if candidateToCheck.hasPrefix(alreadyVisibleText) {
                    effectiveRemainingSuffix = candidateToCheck
                } else if displaySuffix.hasPrefix(" ") && !effectiveRemainingSuffix.hasPrefix(" ") {
                    effectiveRemainingSuffix = " " + effectiveRemainingSuffix
                }
            } else {
                // Background extension / new request while ghost text is visible:
                // MUST start with alreadyVisibleText to prevent visual jumping
                if candidateToCheck.hasPrefix(alreadyVisibleText) || (!normalizedVisible.isEmpty && normalizedCandidate.hasPrefix(normalizedVisible)) {
                    effectiveRemainingSuffix = candidateToCheck
                } else {
                    NSLog("[LangSwitcher] Prefix invariance: discarded extension divergence (new='%@', visible='%@')", displaySuffix, alreadyVisibleText)
                    return
                }
            }
            if displaySuffix.hasPrefix(" ") && !effectiveRemainingSuffix.hasPrefix(" ") {
                effectiveRemainingSuffix = " " + effectiveRemainingSuffix
            }
        }

        let effectiveFieldID = fieldIdentifier ?? accessibilityService.focusedFieldIdentifier() ?? ""
        let target = accessibilityService.captureReplacementTarget()
        let bounds = accessibilityService.caretAndFieldBounds()
        let liveCaret = bounds?.caret ?? caretRect ?? .zero

        let state = ActiveGhostState(
            requestId: effectiveRequestId,
            initialBuffer: initialBuffer ?? wordBuffer,
            remainingSuffix: effectiveRemainingSuffix,
            fullCompletionText: displaySuffix,
            fieldIdentifier: effectiveFieldID,
            suggestionTarget: target,
            caretRect: liveCaret,
            creationDate: Date()
        )
        self.activeGhostState = state
        self.currentAIRequestId = effectiveRequestId
        self.suggestionTarget = target
        if isFinal {
            self.lastCaretContext = accessibilityService.captureCaretContext()
        } else {
            self.lastCaretContext = self.lastCaretContext ?? accessibilityService.captureCaretContext()
        }

        let aiCandidate = AutocompletionCandidate(
            word: wordBuffer.isEmpty ? effectiveRemainingSuffix : (wordBuffer + effectiveRemainingSuffix),
            targetLayoutID: activeLayoutID,
            isCrossLayout: false,
            score: 1500,
            hasScreenContext: hasScreenContext
        )

        if displayMode == .ghostText || displayMode == .both {
            ghostTextController.show(
                candidate: aiCandidate,
                suffix: effectiveRemainingSuffix,
                caretRect: liveCaret,
                fieldRect: bounds?.fieldRect,
                caretProvider: { [weak self] in self?.accessibilityService.caretScreenRect() }
            )
        }

        if displayMode == .popup || displayMode == .both {
            let hint = settingsManager.autoCompletionAcceptKey.shortcutHint(
                customKeyCode: settingsManager.autoCompletionCustomKeyCode,
                customModifiers: settingsManager.autoCompletionCustomModifiers
            )
            var newCandidates = [aiCandidate]
            for c in overlayController.candidates where c.word != aiCandidate.word {
                newCandidates.append(c)
            }
            overlayController.show(
                candidates: Array(newCandidates.prefix(settingsManager.autoCompletionMaxSuggestions)),
                caretRect: liveCaret,
                acceptKeyHint: hint,
                caretProvider: { [weak self] in self?.accessibilityService.caretScreenRect() },
                onSelect: { [weak self] candidate in
                    self?.acceptCandidate(candidate, appendSpace: false, entirePhrase: true)
                }
            )
        }
    }

    func updateAutocompletion(force: Bool = false) {
        guard completionsEnabledForCurrentApp else {
            dismissSuggestionsOnly()
            return
        }

        let currentContext = accessibilityService.captureCaretContext()
        if !force, let snooze = snoozeUntil {
            if let currentField = currentContext?.fieldIdentifier, currentField != snoozeFieldIdentifier {
                snoozeUntil = nil
                snoozeFieldIdentifier = nil
            } else if Date() < snooze {
                overlayController.hide()
                if !settingsManager.isAIAllowed {
                    ghostTextController.hide()
                }
                return
            } else {
                snoozeUntil = nil
                snoozeFieldIdentifier = nil
            }
        }

        // Check gate: do not show completions in secure fields or excluded apps
        if !wordBuffer.isEmpty {
            let focus = accessibilityService.focusedFieldRole()
            let frontmostBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
            guard AutoCorrectionGate.allowsAutoCorrection(
                role: focus?.role,
                subrole: focus?.subrole,
                bundleID: frontmostBundleID,
                excludedBundleIDs: Set(settingsManager.excludedAppBundleIDs)
            ) else {
                dismissSuggestionsOnly()
                return
            }
        }

        if !force {
            guard wordBuffer.count >= settingsManager.autoCompletionMinPrefixLength else {
                overlayController.hide()
                if !settingsManager.isAIAllowed && phraseContinuationAnchor == nil {
                    ghostTextController.hide()
                }
                return
            }
        } else {
            guard !wordBuffer.isEmpty else {
                overlayController.hide()
                if !settingsManager.isAIAllowed && phraseContinuationAnchor == nil {
                    ghostTextController.hide()
                }
                return
            }
        }

        guard !NSApp.isActive else {
            dismissSuggestionsOnly()
            return
        }

        let activeLayoutID = KeyboardLayoutDetector.getCurrentLayout()?.id ?? "com.apple.keylayout.US"
        let currentBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        let candidates = autocompletionEngine.suggest(
            for: wordBuffer,
            previousWord: previousWord,
            activeLayoutID: activeLayoutID,
            enabledLayouts: settingsManager.enabledLayouts,
            maxSuggestions: settingsManager.autoCompletionMaxSuggestions,
            includeCrossLayout: settingsManager.autoCompletionIncludeCrossLayout,
            allowProfanity: settingsManager.autoCompletionSuggestProfanity,
            bundleID: currentBundleID
        )

        guard !candidates.isEmpty else {
            overlayController.hide()
            if !settingsManager.isAIAllowed && phraseContinuationAnchor == nil {
                ghostTextController.hide()
            }
            return
        }

        if !settingsManager.isAIAllowed || activeGhostState == nil {
            suggestionTarget = accessibilityService.captureReplacementTarget()
            lastCaretContext = currentContext ?? accessibilityService.captureCaretContext()
        }
        let bounds = accessibilityService.caretAndFieldBounds()
        let caretRect = bounds?.caret
        let displayMode = settingsManager.autoCompletionDisplayMode

        // 1. Ghost text inline tail
        if displayMode == .ghostText || displayMode == .both {
            if settingsManager.isAIAllowed {
                // When AI predictive mode is active, do not touch ghostTextController here.
                // Ghost text is exclusively owned by AI inference and activeGhostState.
            } else if let topCandidate = candidates.first,
               topCandidate.word.lowercased().hasPrefix(wordBuffer.lowercased()),
               topCandidate.word.count > wordBuffer.count {
                let suffixIndex = topCandidate.word.index(topCandidate.word.startIndex, offsetBy: wordBuffer.count)
                let suffix = String(topCandidate.word[suffixIndex...])
                ghostTextController.show(
                    candidate: topCandidate,
                    suffix: suffix,
                    caretRect: caretRect,
                    fieldRect: bounds?.fieldRect,
                    caretProvider: { [weak self] in self?.accessibilityService.caretScreenRect() }
                )
            } else {
                ghostTextController.hide()
            }
        } else {
            if !settingsManager.isAIAllowed {
                ghostTextController.hide()
            }
        }

        // 2. Floating popup HUD
        if displayMode == .popup || displayMode == .both {
            let hint = settingsManager.autoCompletionAcceptKey.shortcutHint(
                customKeyCode: settingsManager.autoCompletionCustomKeyCode,
                customModifiers: settingsManager.autoCompletionCustomModifiers
            )
            overlayController.show(
                candidates: candidates,
                caretRect: caretRect ?? accessibilityService.focusedFieldScreenRect(),
                acceptKeyHint: hint,
                caretProvider: { [weak self] in self?.accessibilityService.caretScreenRect() },
                onSelect: { [weak self] candidate in
                    self?.acceptCandidate(candidate, appendSpace: false, entirePhrase: true)
                }
            )
        } else {
            overlayController.hide()
        }
    }

    /// Accept and insert the candidate completion.
    /// If entirePhrase is false and candidate has multiple words, only the first word is inserted
    /// and the remaining words stay in ghost text.
    @discardableResult
    func acceptCandidate(_ candidate: AutocompletionCandidate, appendSpace: Bool, entirePhrase: Bool = true,
                         failureEvent: CGEvent? = nil) -> Bool {
        guard !isProcessingCorrection,
              !wordBuffer.isEmpty || phraseContinuationAnchor != nil || ghostTextController.isVisible || overlayController.isVisible || activeGhostState != nil else {
            dismissAutocompletion()
            return false
        }
        
        // A suggestion belongs to the field captured when it was presented.
        // Never redirect an old suggestion to a newly focused editor.
        guard let validTarget = activeGhostState?.suggestionTarget ?? suggestionTarget,
              accessibilityService.isCurrentReplacementTarget(validTarget) else {
            NSLog("[LangSwitcher] Completion rejected: missing or changed target")
            dismissAutocompletion()
            return false
        }

        // Stale check via CaretContext: verify field hasn't changed and caret hasn't jumped backwards
        let currentCtx = accessibilityService.captureCaretContext()
        if let lastCtx = lastCaretContext, let currentCtx = currentCtx {
            guard currentCtx.fieldIdentifier == lastCtx.fieldIdentifier,
                  currentCtx.selectedText.isEmpty,
                  currentCtx.caretLocation >= lastCtx.caretLocation else {
                NSLog("[LangSwitcher] Completion rejected: changed caret or selection")
                dismissAutocompletion()
                return false
            }
        }
        
        let textPlan = CompletionAcceptanceText(candidate: candidate.word, typedPrefix: wordBuffer,
            entirePhrase: entirePhrase, appendSpace: appendSpace,
            includePunctuation: settingsManager.autoCompletionIncludeTrailingPunctuation)
        let insertionText = textPlan.insertion
        let remainingPhrase = textPlan.remaining

        let acceptance = PhraseAcceptancePlan(buffer: wordBuffer, continuationAnchor: phraseContinuationAnchor,
                                              insertion: insertionText)
        let precedingWord = previousWord
        let accessibility = accessibilityService
        
        guard let operation = replacementSession.begin() else { return false }
        let replay = failureEvent?.copy()
        var submitting = true
        var rejected = false
        func recoverShortcut(after outcome: CompletionPasteOutcome) {
            guard outcome.shouldReplayShortcut, !submitting, let replay,
                  accessibility.isCurrentReplacementTarget(validTarget) else { return }
            replay.setIntegerValueField(.eventSourceUserData, value: Self.syntheticEventMarker)
            replay.post(tap: .cgAnnotatedSessionEventTap)
        }
        // Same-layout completions only append their missing tail. Do not select
        // the prefix: web editors may apply AX selection changes asynchronously.
        let suffix = acceptance.appendingSuffix
        let expected = suffix == nil ? acceptance.expected : ""
        let replacement = suffix ?? acceptance.replacement
        if let context = currentCtx {
            guard context.selectedText.isEmpty,
                  (suffix != nil && context.fullTextLength == 0
                   || (suffix != nil && phraseContinuationAnchor != nil)
                   || context.textBeforeCaret.hasSuffix(acceptance.expected)) else {
                NSLog("[LangSwitcher] Completion rejected: prefix unavailable or changed")
                replacementSession.finish(operation)
                dismissAutocompletion()
                return false
            }
        } else {
            // In Electron / Chromium custom webviews (e.g. Antigravity), captureCaretContext()
            // may return nil if kAXSelectedTextRangeAttribute is temporarily omitted after a paste.
            // Allow appending continuations at caret as long as the replacement target is still valid.
            guard suffix != nil else {
                NSLog("[LangSwitcher] Completion rejected: no AX caret context for full replacement")
                replacementSession.finish(operation)
                dismissAutocompletion()
                return false
            }
        }

        // Transition state immediately for word-by-word continuations so that
        // the second word remains visible and interactive in both ghost text and popup
        // even while Electron/Chromium is still processing the asynchronous Cmd+V paste.
        self.wordBuffer = ""
        self.typeAheadHandledCount = 0
        let acceptedWord = insertionText.trimmingCharacters(in: .whitespaces)
        self.previousWord = acceptedWord.lowercased()

        let displayMode = self.settingsManager.autoCompletionDisplayMode
        if let remaining = remainingPhrase, !remaining.isEmpty {
            self.phraseContinuationAnchor = insertionText
            let remainingCandidate = AutocompletionCandidate(
                word: remaining,
                targetLayoutID: candidate.targetLayoutID,
                isCrossLayout: false,
                score: candidate.score,
                hasScreenContext: candidate.hasScreenContext
            )
            self.suggestionTarget = validTarget
            self.lastCaretContext = currentCtx ?? self.lastCaretContext
            let continuationRequestId = UUID()
            self.currentAIRequestId = continuationRequestId
            let fieldID = currentCtx?.fieldIdentifier ?? self.activeGhostState?.fieldIdentifier ?? self.accessibilityService.focusedFieldIdentifier() ?? ""
            let anchorCaret = self.accessibilityService.caretScreenRect() ?? self.activeGhostState?.caretRect
            let frontmostBundleID = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
            let estimatedCaret: CGRect? = {
                guard let anchor = anchorCaret, GhostTextOverlayController.isValidCaretRect(anchor) else { return nil }
                let font = EditorFontCustomizer.shared.font(for: frontmostBundleID, caretHeight: anchor.height)
                    ?? NSFont.systemFont(ofSize: anchor.height > 10 ? max(12.0, min(16.0, anchor.height - 3)) : 13.5)
                let advance = (insertionText as NSString).size(withAttributes: [.font: font]).width
                return CGRect(
                    x: anchor.origin.x + advance,
                    y: anchor.origin.y,
                    width: anchor.width,
                    height: anchor.height
                )
            }()

            self.activeGhostState = ActiveGhostState(
                requestId: continuationRequestId,
                initialBuffer: "",
                remainingSuffix: remaining,
                fullCompletionText: remaining,
                fieldIdentifier: fieldID,
                suggestionTarget: validTarget,
                caretRect: estimatedCaret ?? anchorCaret ?? .zero,
                creationDate: Date()
            )
            if displayMode == .ghostText || displayMode == .both {
                self.ghostTextController.showContinuation(
                    candidate: remainingCandidate,
                    suffix: remaining,
                    staleAnchor: anchorCaret,
                    estimatedCaret: estimatedCaret,
                    bundleID: frontmostBundleID,
                    caretProvider: { [weak self] in self?.accessibilityService.caretScreenRect() },
                    isCurrent: { [weak self] in
                        guard let self, self.phraseContinuationAnchor == insertionText else { return false }
                        return self.accessibilityService.isCurrentReplacementTarget(validTarget)
                    }
                )
            } else {
                self.ghostTextController.hide()
            }
            if displayMode == .popup || displayMode == .both {
                let hint = self.settingsManager.autoCompletionAcceptKey.shortcutHint(
                    customKeyCode: self.settingsManager.autoCompletionCustomKeyCode,
                    customModifiers: self.settingsManager.autoCompletionCustomModifiers
                )
                self.overlayController.showContinuation(
                    candidates: [remainingCandidate],
                    staleAnchor: anchorCaret,
                    estimatedCaret: estimatedCaret,
                    acceptKeyHint: hint,
                    caretProvider: { [weak self] in self?.accessibilityService.caretScreenRect() },
                    isCurrent: { [weak self] in
                        guard let self, self.phraseContinuationAnchor == insertionText else { return false }
                        return self.accessibilityService.isCurrentReplacementTarget(validTarget)
                    },
                    onSelect: { [weak self] cand in
                        self?.acceptCandidate(cand, appendSpace: false, entirePhrase: true)
                    }
                )
            } else {
                self.overlayController.hide()
            }
        } else {
            self.dismissAutocompletion()
        }

        let appliedReceipt: (Bool) -> Void = { [weak self] applied in
                guard let self, self.replacementSession.isCurrent(operation) else { return }
                self.replacementSession.finish(operation)
                guard applied else {
                    NSLog("[LangSwitcher] Completion paste unconfirmed; acceptance key remains consumed")
                    recoverShortcut(after: .unconfirmed)
                    return
                }
                self.adaptiveStore.recordWordUsage(word: acceptedWord, after: precedingWord)
                if candidate.isCrossLayout { KeyboardLayoutDetector.switchToLayout(candidate.targetLayoutID) }
                self.playCorrectionFeedback()
                self.settingsManager.recordSavedText(inserted: acceptance.replacement.count, typed: acceptance.expected.count)
                CompletionStatsTracker.shared.recordAcceptedCompletion(insertedText: acceptance.replacement, typedPrefix: acceptance.expected)

                if let remaining = remainingPhrase, !remaining.isEmpty, self.phraseContinuationAnchor == insertionText {
                    self.suggestionTarget = self.accessibilityService.captureReplacementTarget() ?? validTarget
                    self.lastCaretContext = self.accessibilityService.captureCaretContext() ?? self.lastCaretContext
                    let anchorCaret = self.activeGhostState?.caretRect
                    if let bounds = self.accessibilityService.caretAndFieldBounds(),
                       GhostTextOverlayController.hasCaretAdvanced(from: anchorCaret, to: bounds.caret) {
                        let liveCaret = bounds.caret
                        self.activeGhostState?.caretRect = liveCaret
                        if displayMode == .ghostText || displayMode == .both,
                           let currentCand = self.ghostTextController.currentCandidate {
                            self.ghostTextController.show(
                                candidate: currentCand,
                                suffix: remaining,
                                caretRect: liveCaret,
                                fieldRect: bounds.fieldRect,
                                caretProvider: { [weak self] in self?.accessibilityService.caretScreenRect() }
                            )
                        }
                        if (displayMode == .popup || displayMode == .both) {
                            let remainingCand = AutocompletionCandidate(
                                word: remaining,
                                targetLayoutID: candidate.targetLayoutID,
                                isCrossLayout: false,
                                score: candidate.score,
                                hasScreenContext: candidate.hasScreenContext
                            )
                            let hint = self.settingsManager.autoCompletionAcceptKey.shortcutHint(
                                customKeyCode: self.settingsManager.autoCompletionCustomKeyCode,
                                customModifiers: self.settingsManager.autoCompletionCustomModifiers
                            )
                            self.overlayController.show(
                                candidates: self.overlayController.candidates.isEmpty ? [remainingCand] : self.overlayController.candidates,
                                caretRect: liveCaret,
                                acceptKeyHint: hint,
                                caretProvider: { [weak self] in self?.accessibilityService.caretScreenRect() },
                                onSelect: { [weak self] cand in
                                    self?.acceptCandidate(cand, appendSpace: false, entirePhrase: true)
                                }
                            )
                        }
                    }
                }
        }
        if suffix != nil {
            let dispatched = accessibility.pasteContinuationAtCaret(replacement, target: validTarget,
                                                                   onApplied: appliedReceipt)
            if !dispatched {
                rejected = true
                replacementSession.finish(operation)
                dismissAutocompletion()
            }
        } else {
            accessibility.pasteVerifiedSuffix(expected, with: replacement, target: validTarget,
                completion: { [weak self] dispatched in
                    guard !dispatched, let self else { return }
                    rejected = true
                    self.replacementSession.finish(operation)
                    self.dismissAutocompletion()
                    recoverShortcut(after: .notDispatched)
                }, onApplied: appliedReceipt)
        }
        submitting = false
        return !rejected
    }

    // MARK: - Auto-Correction Logic

    /// Check the buffered word and correct it if it looks like wrong layout.
    private func triggerCheckAndCorrect(triggerChar: Character) {
        let bufferedWord = wordBuffer
        wordBuffer = ""
        guard !isProcessingCorrection, !NSApp.isActive else { return }

        let focus = accessibilityService.focusedFieldRole()
        let allowed = AutoCorrectionGate.allowsAutoCorrection(
            role: focus?.role,
            subrole: focus?.subrole,
            bundleID: NSWorkspace.shared.frontmostApplication?.bundleIdentifier,
            text: bufferedWord,
            excludedBundleIDs: Set(settingsManager.excludedAppBundleIDs)
        )
        // Conversion and spell checking log text. The gate must run before either
        // the ambiguous-key classifier or dictionary validation can inspect it.
        guard let token = CorrectionToken.analyze(bufferedWord, whenAllowed: allowed,
            ambiguous: isAlternativeLetterKey, validConversion: { candidate in
                guard let info = self.textConverter.convertSelectedTextWithInfo(candidate),
                      let lang = self.settingsManager.enabledLayouts.first(where: { $0.id == info.targetLayoutID })?.languageCode
                else { return false }
                return self.spellCheckService.isValidWord(info.text, language: lang)
            }) else {
            previousWord = nil
            return
        }
        let word = token.word
        guard !AutoCorrectionGate.isPotentialSecret(word) else {
            previousWord = nil
            return
        }
        if !word.isEmpty { previousWord = word.lowercased() }

        let axBefore = accessibilityService.captureCaretContext()?.textBeforeCaret
        let withTrigger = bufferedWord + String(triggerChar)
        let textBeforeWord: String
        if let ax = axBefore, !ax.isEmpty {
            if ax.hasSuffix(withTrigger) {
                textBeforeWord = String(ax.dropLast(withTrigger.count))
            } else if ax.hasSuffix(bufferedWord) {
                textBeforeWord = String(ax.dropLast(bufferedWord.count))
            } else if recentTextBuffer.hasSuffix(bufferedWord) {
                textBeforeWord = String(recentTextBuffer.dropLast(bufferedWord.count))
            } else {
                textBeforeWord = recentTextBuffer
            }
        } else if recentTextBuffer.hasSuffix(bufferedWord) {
            textBeforeWord = String(recentTextBuffer.dropLast(bufferedWord.count))
        } else {
            textBeforeWord = recentTextBuffer
        }

        // Check for comma before Russian coordinating conjunctions «а» and «но»
        if settingsManager.autoCorrectionCommaBeforeConjunctions && triggerChar == " " {
            if SmartPunctuationEngine.shouldInsertCommaBeforeConjunction(word: word, precedingText: textBeforeWord) {
                NSLog("[LangSwitcher] AutoCorrection: inserting comma before conjunction '\(word)'")
                performCheckedReplacement(expected: " " + bufferedWord + " ",
                                          replacement: ", " + bufferedWord + " ") { [weak self] _ in
                    guard let self else { return }
                    self.previousWord = word.lowercased()
                    self.playCorrectionFeedback()
                    self.settingsManager.recordAutoCorrection(charCount: 2)
                }
                return
            }
        }

        guard word.count >= 2 else { return }

        // Veto: User Dictionary words are intentional and must never be auto-corrected or converted
        if UserDictionary.shared.contains(word) {
            NSLog("[LangSwitcher] AutoCorrection: '\(word)' is in UserDictionary, skipping all corrections")
            return
        }

        // Retyping after deletion: if user re-typed the original word from a recent auto-correction, learn it!
        if checkAndLearnRetypedWord(word) {
            return
        }

        NSLog("[LangSwitcher] AutoCorrection: checking word '\(word)' (trigger='\(triggerChar)')")

        // Step 1: Try layout conversion if the word looks like wrong layout
        if textConverter.looksLikeWrongLayout(word),
           let result = textConverter.convertSelectedTextWithInfo(word) {
            var convertedWord = result.text
            if settingsManager.autoCorrectionFixTwoInitialCapitals,
               let fixedCapitals = textConverter.fixTwoInitialCapitals(convertedWord) {
                convertedWord = fixedCapitals
            }
            if settingsManager.autoCorrectionCapitalizeSentences,
               let capitalized = SmartPunctuationEngine.capitalizeAfterSentence(word: convertedWord, precedingText: textBeforeWord) {
                convertedWord = capitalized
            }

            var isLayoutConversionValid = true
            if settingsManager.autoCorrectionUseSpellCheck {
                let layouts = settingsManager.enabledLayouts
                let targetLang = layouts.first(where: { $0.id == result.targetLayoutID })?.languageCode

                if let lang = targetLang {
                    if !spellCheckService.isValidWord(convertedWord, language: lang) {
                        NSLog("[LangSwitcher] AutoCorrection: '\(convertedWord)' not valid in '\(lang)', skipping layout conversion")
                        isLayoutConversionValid = false
                    }
                }

                let sourceLangs = layouts.map(\.languageCode)
                if spellCheckService.isValidWordInAnyLanguage(word, languages: sourceLangs) {
                    NSLog("[LangSwitcher] AutoCorrection: '\(word)' is valid in source language, skipping layout conversion")
                    isLayoutConversionValid = false
                }
            }

            if isLayoutConversionValid {
                NSLog("[LangSwitcher] AutoCorrection: layout converted '\(word)' → '\(convertedWord)'")
                let currentLayout = KeyboardLayoutDetector.getCurrentLayout()?.id
                let targetLayout = result.targetLayoutID
                let switchLayout = self.settingsManager.autoCorrectionSwitchLayout
                let expectedText = bufferedWord + String(triggerChar)
                let replacementText = token.prefix + convertedWord + token.punctuation + String(triggerChar)
                performCheckedReplacement(expected: expectedText,
                                          replacement: replacementText) { [weak self] _ in
                    guard let self else { return }
                    self.previousWord = convertedWord.lowercased()
                    if switchLayout {
                        NSLog("[LangSwitcher] AutoCorrection: switching layout to target '\(targetLayout)'")
                        KeyboardLayoutDetector.switchToLayout(targetLayout)
                    }
                    self.recordAppliedCorrection(
                        originalWord: word,
                        replacedWord: convertedWord,
                        fullExpected: expectedText,
                        fullReplacement: replacementText,
                        switchedFromLayoutID: switchLayout ? currentLayout : nil,
                        switchedToLayoutID: switchLayout ? targetLayout : nil
                    )
                    self.playCorrectionFeedback()
                    self.settingsManager.recordAutoCorrection(charCount: bufferedWord.count)
                }
                return
            }
        }

        // Step 2: Check for Two Initial Capitals in current layout (e.g. "ПРобую" -> "Пробую", "THis" -> "This")
        if settingsManager.autoCorrectionFixTwoInitialCapitals,
           let fixedWord = textConverter.fixTwoInitialCapitals(word) {
            NSLog("[LangSwitcher] AutoCorrection: checking two initial capitals: '\(word)' → '\(fixedWord)'")

            if settingsManager.autoCorrectionUseSpellCheck {
                let layouts = settingsManager.enabledLayouts
                let langs = layouts.map(\.languageCode)

                let inSpellChecker = spellCheckService.isValidWordInAnyLanguage(fixedWord, languages: langs)
                let inWordlists = LanguageWordlists.contains(word: fixedWord)
                if !inSpellChecker && !inWordlists {
                    NSLog("[LangSwitcher] AutoCorrection: '\(fixedWord)' not valid in spellchecker or wordlists, skipping capital fix")
                    return
                }
            }

            NSLog("[LangSwitcher] AutoCorrection: two initial capitals corrected: '\(word)' → '\(fixedWord)'")
            let expectedText = bufferedWord + String(triggerChar)
            let replacementText = token.prefix + fixedWord + token.punctuation + String(triggerChar)
            performCheckedReplacement(expected: expectedText,
                                      replacement: replacementText) { [weak self] _ in
                guard let self else { return }
                self.previousWord = fixedWord.lowercased()
                self.recordAppliedCorrection(
                    originalWord: word,
                    replacedWord: fixedWord,
                    fullExpected: expectedText,
                    fullReplacement: replacementText
                )
                self.playCorrectionFeedback()
                self.settingsManager.recordAutoCorrection(charCount: bufferedWord.count)
            }
            return
        }

        // Step 3: Check for accidental Caps Lock (e.g. "пРИВЕТ" -> "Привет", "hELLO" -> "Hello")
        if settingsManager.autoCorrectionFixCapsLockErrors,
           let fixedCaps = SmartPunctuationEngine.fixCapsLockError(word) {
            NSLog("[LangSwitcher] AutoCorrection: checking Caps Lock error: '\(word)' → '\(fixedCaps)'")
            var isCapsValid = true
            if settingsManager.autoCorrectionUseSpellCheck {
                let layouts = settingsManager.enabledLayouts
                let langs = layouts.map(\.languageCode)
                let inSpell = spellCheckService.isValidWordInAnyLanguage(fixedCaps, languages: langs)
                let inList = LanguageWordlists.contains(word: fixedCaps)
                if !inSpell && !inList {
                    isCapsValid = false
                }
            }
            if isCapsValid {
                NSLog("[LangSwitcher] AutoCorrection: Caps Lock corrected: '\(word)' → '\(fixedCaps)'")
                let expectedText = bufferedWord + String(triggerChar)
                let replacementText = token.prefix + fixedCaps + token.punctuation + String(triggerChar)
                performCheckedReplacement(expected: expectedText,
                                          replacement: replacementText) { [weak self] _ in
                    guard let self else { return }
                    self.previousWord = fixedCaps.lowercased()
                    self.recordAppliedCorrection(
                        originalWord: word,
                        replacedWord: fixedCaps,
                        fullExpected: expectedText,
                        fullReplacement: replacementText
                    )
                    self.playCorrectionFeedback()
                    self.settingsManager.recordAutoCorrection(charCount: bufferedWord.count)
                }
                return
            }
        }

        // Step 3b: Check for mechanical word typos (e.g. "большоей" -> "большой", "поставитьл" -> "поставить", "привте" -> "привет")
        if settingsManager.autoCorrectionFixTypos {
            let layouts = settingsManager.enabledLayouts
            let langs = layouts.map(\.languageCode)
            if var fixedTypo = TypoCorrectionEngine.correctTypo(word, languages: langs, spellCheckService: spellCheckService) {
                if settingsManager.autoCorrectionCapitalizeSentences,
                   let capTypo = SmartPunctuationEngine.capitalizeAfterSentence(word: fixedTypo, precedingText: textBeforeWord) {
                    fixedTypo = capTypo
                }
                NSLog("[LangSwitcher] AutoCorrection: typo corrected: '\(word)' → '\(fixedTypo)'")
                let expectedText = bufferedWord + String(triggerChar)
                let replacementText = token.prefix + fixedTypo + token.punctuation + String(triggerChar)
                performCheckedReplacement(expected: expectedText,
                                          replacement: replacementText) { [weak self] _ in
                    guard let self else { return }
                    self.previousWord = fixedTypo.lowercased()
                    self.recordAppliedCorrection(
                        originalWord: word,
                        replacedWord: fixedTypo,
                        fullExpected: expectedText,
                        fullReplacement: replacementText
                    )
                    self.playCorrectionFeedback()
                    self.settingsManager.recordAutoCorrection(charCount: bufferedWord.count)
                }
                return
            }
        }

        // Step 4: Capitalize after sentence terminator or start of line (e.g. ". привет" -> ". Привет")
        if settingsManager.autoCorrectionCapitalizeSentences,
           let capitalized = SmartPunctuationEngine.capitalizeAfterSentence(word: word, precedingText: textBeforeWord) {
            NSLog("[LangSwitcher] AutoCorrection: checking sentence capitalization: '\(word)' → '\(capitalized)'")
            var isCapValid = true
            if settingsManager.autoCorrectionUseSpellCheck {
                let layouts = settingsManager.enabledLayouts
                let langs = layouts.map(\.languageCode)
                let inSpell = spellCheckService.isValidWordInAnyLanguage(capitalized, languages: langs)
                let inList = LanguageWordlists.contains(word: capitalized)
                if !inSpell && !inList {
                    isCapValid = false
                }
            }
            if isCapValid {
                NSLog("[LangSwitcher] AutoCorrection: sentence capitalized: '\(word)' → '\(capitalized)'")
                let expectedText = bufferedWord + String(triggerChar)
                let replacementText = token.prefix + capitalized + token.punctuation + String(triggerChar)
                performCheckedReplacement(expected: expectedText,
                                          replacement: replacementText) { [weak self] _ in
                    guard let self else { return }
                    self.previousWord = capitalized.lowercased()
                    self.recordAppliedCorrection(
                        originalWord: word,
                        replacedWord: capitalized,
                        fullExpected: expectedText,
                        fullReplacement: replacementText
                    )
                    self.playCorrectionFeedback()
                    self.settingsManager.recordAutoCorrection(charCount: 1)
                }
                return
            }
        }

        NSLog("[LangSwitcher] AutoCorrection: '\(word)' does not need correction")
    }

    // MARK: - Revert & User Dictionary Auto-Learning

    func recordAppliedCorrection(
        originalWord: String,
        replacedWord: String,
        fullExpected: String,
        fullReplacement: String,
        switchedFromLayoutID: String? = nil,
        switchedToLayoutID: String? = nil
    ) {
        let applied = AppliedAutoCorrection(
            originalWord: originalWord,
            replacedWord: replacedWord,
            fullExpected: fullExpected,
            fullReplacement: fullReplacement,
            switchedFromLayoutID: switchedFromLayoutID,
            switchedToLayoutID: switchedToLayoutID,
            timestamp: Date()
        )
        self.pendingRevertCorrection = applied
        self.lastAutoCorrection = applied
        if !recentTextBuffer.hasSuffix(fullReplacement) {
            if recentTextBuffer.hasSuffix(fullExpected) {
                recentTextBuffer.removeLast(fullExpected.count)
            }
            recentTextBuffer.append(fullReplacement)
        }
    }

    @discardableResult
    func revertPendingCorrection() -> Bool {
        guard let pending = pendingRevertCorrection else { return false }
        pendingRevertCorrection = nil
        lastAutoCorrection = nil

        NSLog("[LangSwitcher] AutoCorrection: reverting '\(pending.replacedWord)' → '\(pending.originalWord)'")

        // 1. Immediately teach user dictionary so this word is never modified again
        let learned = UserDictionary.shared.learn(pending.originalWord)
        NSLog("[LangSwitcher] AutoCorrection: learned '\(pending.originalWord)' to UserDictionary: \(learned)")

        // 2. Revert layout switch if one occurred
        if let from = pending.switchedFromLayoutID, pending.switchedToLayoutID != nil {
            NSLog("[LangSwitcher] AutoCorrection: reverting layout switch back to '\(from)'")
            KeyboardLayoutDetector.switchToLayout(from)
        }

        // 3. Update internal buffers
        if recentTextBuffer.hasSuffix(pending.fullReplacement) {
            recentTextBuffer.removeLast(pending.fullReplacement.count)
            recentTextBuffer.append(pending.fullExpected)
        }
        wordBuffer = ""
        previousWord = pending.originalWord.lowercased()

        // 4. Revert text in target editor
        performCheckedReplacement(expected: pending.fullReplacement, replacement: pending.fullExpected) { [weak self] applied in
            guard let self else { return }
            if applied {
                self.playCorrectionFeedback()
            }
        }
        return true
    }

    /// Checks if the word is a retype of a recently corrected word. If so, learns it into UserDictionary and returns true.
    @discardableResult
    func checkAndLearnRetypedWord(_ word: String) -> Bool {
        guard let last = lastAutoCorrection,
              Date().timeIntervalSince(last.timestamp) < 60.0,
              last.originalWord.lowercased() == word.lowercased() else {
            return false
        }
        NSLog("[LangSwitcher] AutoCorrection: user re-typed '\(word)' (previously corrected to '\(last.replacedWord)'). Learning to UserDictionary and abstaining.")
        UserDictionary.shared.learn(word)
        lastAutoCorrection = nil
        pendingRevertCorrection = nil
        playCorrectionFeedback()
        return true
    }

    private func playCorrectionFeedback() {
        if settingsManager.playSounds { NSSound(named: .init("Tink"))?.play() }
        settingsManager.incrementConversionCount()
    }

    @discardableResult
    private func performCheckedReplacement(expected: String, replacement: String, target existingTarget: AccessibilityService.ReplacementTarget? = nil, onSuccess: @escaping (Bool) -> Void) -> Bool {
        guard let operation = replacementSession.begin() else { return false }
        completionRefresh.cancel()

        guard let target = existingTarget ?? accessibilityService.captureReplacementTarget() else {
            // Target app does not expose accessible text node (e.g. Electron / Chromium web view).
            // Fall back to synthetic backspaces + paste!
            NSLog("[LangSwitcher] performCheckedReplacement: no AX target, using backspace fallback for '\(expected)' → '\(replacement)'")
            accessibilityService.replaceWithBackspaces(count: expected.count, replacement: replacement) { [weak self] applied in
                guard let self, self.replacementSession.isCurrent(operation) else { return }
                self.replacementSession.finish(operation)
                if applied { onSuccess(true) }
            }
            return true
        }

        // 1. Immediate path: replace immediately if the editor has already committed the delimiter
        if accessibilityService.replaceVerifiedSuffix(expected, with: replacement, target: target,
                                                          preferPasteInWebEditors: true) {
            replacementSession.finish(operation)
            onSuccess(true)
            return true
        }

        // 2. Delayed path: wait 35ms for the delimiter to reach web/remote editors
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.035) { [weak self] in
            guard let self else { return }
            guard self.replacementSession.isCurrent(operation) else { return }
            guard self.accessibilityService.isCurrentReplacementTarget(target) else {
                self.replacementSession.finish(operation)
                return
            }
            if self.accessibilityService.replaceVerifiedSuffix(expected, with: replacement, target: target,
                                                              preferPasteInWebEditors: true) {
                self.replacementSession.finish(operation)
                onSuccess(true)
            } else {
                // Some web editors expose a writable AXSelectedText but ignore
                // its setter. Paste only into a freshly verified selection.
                self.accessibilityService.pasteVerifiedSuffix(expected, with: replacement, target: target) { [weak self] applied in
                    guard let self, self.replacementSession.isCurrent(operation) else { return }
                    if applied {
                        self.replacementSession.finish(operation)
                        onSuccess(true)
                    } else {
                        // AX paste verification failed (common in Electron / web contenteditable).
                        // Fall back to synthetic backspaces + paste!
                        NSLog("[LangSwitcher] performCheckedReplacement: AX paste failed, falling back to backspaces for '\(expected)' → '\(replacement)'")
                        self.accessibilityService.replaceWithBackspaces(count: expected.count, replacement: replacement) { [weak self] backspaceApplied in
                            guard let self, self.replacementSession.isCurrent(operation) else { return }
                            self.replacementSession.finish(operation)
                            if backspaceApplied { onSuccess(true) }
                        }
                    }
                }
            }
        }
        return true
    }

    // MARK: - Character Extraction

    /// Extract typed characters from a CGEvent.
    nonisolated private func getCharactersFromEvent(_ event: CGEvent) -> String? {
        var length = 0
        event.keyboardGetUnicodeString(maxStringLength: 0, actualStringLength: &length, unicodeString: nil)
        guard length > 0 else { return nil }

        var buffer = [UniChar](repeating: 0, count: length)
        event.keyboardGetUnicodeString(maxStringLength: length, actualStringLength: &length, unicodeString: &buffer)
        return String(utf16CodeUnits: buffer, count: length)
    }


}

// MARK: - CGEvent Tap Callback

/// C-compatible callback for the CGEvent tap.
/// Must be a free function (not a method) because CGEvent.tapCreate requires a C function pointer.
private func autoCorrectionEventCallback(
    proxy: CGEventTapProxy,
    type: CGEventType,
    event: CGEvent,
    userInfo: UnsafeMutableRawPointer?
) -> Unmanaged<CGEvent>? {

    // Ignore synthetic events generated by our own auto-correction service to prevent feedback loops
    if event.getIntegerValueField(.eventSourceUserData) == AutoCorrectionService.syntheticEventMarker {
        return Unmanaged.passUnretained(event)
    }

    // Handle tap disabled events (system can disable taps under load)
    if type == .tapDisabledByTimeout || type == .tapDisabledByUserInput {
        // Re-enable the tap immediately
        if let userInfo = userInfo {
            let service = Unmanaged<AutoCorrectionService>.fromOpaque(userInfo).takeUnretainedValue()
            if Thread.isMainThread {
                MainActor.assumeIsolated {
                    service.reEnableEventTap()
                }
            } else {
                DispatchQueue.main.async {
                    service.reEnableEventTap()
                }
            }
        }
        return Unmanaged.passUnretained(event)
    }

    guard let userInfo = userInfo else {
        return Unmanaged.passUnretained(event)
    }

    let service = Unmanaged<AutoCorrectionService>.fromOpaque(userInfo).takeUnretainedValue()

    guard type == .keyDown || type == .keyUp else {
        return Unmanaged.passUnretained(event)
    }

    // Check if the key should be consumed by active autocompletion overlay.
    // CRITICAL: NEVER call DispatchQueue.main.sync inside a CGEventTap callback!
    // Any synchronous dispatch to main queue will deadlock WindowServer whenever the main thread is busy.
    let intercepted: Bool
    if Thread.isMainThread {
        intercepted = MainActor.assumeIsolated {
            service.interceptCompletionKeyEvent(event)
        }
    } else {
        intercepted = false
    }

    if intercepted {
        return nil
    }

    if type == .keyDown { service.handleKeyEvent(event) }

    // Pass the event through if not consumed
    return Unmanaged.passUnretained(event)
}

// A policy shared by the watchdog and tests. No inactivity timeout: a user may
// simply not be typing, and that must never cause repeated tap recreation.
enum ServiceRecovery {
    enum Action: Equatable { case disable, waitForPermission, start, enable, none }

    static func action(enabled: Bool, trusted: Bool, valid: Bool, running: Bool) -> Action {
        guard enabled else { return .disable }
        guard trusted else { return .waitForPermission }
        guard valid else { return .start }
        return running ? .none : .enable
    }
}


/// Ambiguous physical keys (e.g. semicolon → ж) belong inside a word. At the
/// end, keep punctuation literal unless the complete converted word is valid.
enum CorrectionToken {
    static func isAlternativeLetter(_ char: Character, source: String, targets: [String]) -> Bool {
        guard !char.isWhitespace, !char.isLetter, !char.isNumber else { return false }
        return targets.contains { target in
            guard target != source,
                  let mapped = LayoutMapper.convert(text: String(char), from: source, to: target) else { return false }
            return mapped.count == 1 && mapped.first?.isLetter == true
        }
    }

    struct Parts {
        let prefix: String
        let word: String
        let punctuation: String
    }

    /// Keep text-processing closures lazy: protected/excluded fields must never
    /// reach converters or spell checkers that can log the supplied text.
    static func analyze(_ buffer: String, whenAllowed allowed: Bool,
                        ambiguous: (Character) -> Bool,
                        validConversion: (String) -> Bool) -> Parts? {
        guard allowed else { return nil }
        return split(buffer, ambiguous: ambiguous, validConversion: validConversion)
    }

    static func split(_ buffer: String, ambiguous: (Character) -> Bool,
                      validConversion: (String) -> Bool) -> Parts {
        let isQuote: (Character) -> Bool = { $0 == "\"" || $0 == "'" }
        let hasLeadingQuote = buffer.first.map(isQuote) ?? false
        let hasAmbiguousEnd = buffer.last.map(ambiguous) ?? false
        guard hasLeadingQuote || hasAmbiguousEnd, !validConversion(buffer) else {
            return Parts(prefix: "", word: buffer, punctuation: "")
        }
        // Try trimming sentence punctuation while retaining the initial key.
        // "njn. must become Этот., not a literal quote followed by тот.
        var unquotedWord = buffer
        var sentencePunctuation = ""
        while let last = unquotedWord.last, ambiguous(last) {
            sentencePunctuation.insert(unquotedWord.removeLast(), at: sentencePunctuation.startIndex)
            if !unquotedWord.isEmpty, validConversion(unquotedWord) {
                return Parts(prefix: "", word: unquotedWord, punctuation: sentencePunctuation)
            }
        }
        var core = buffer
        var prefix = ""
        // A recognized conversion such as "nj → Это was retained above.
        // Otherwise preserve opening quotation marks literally.
        while let first = core.first, isQuote(first) {
            prefix.append(core.removeFirst())
        }
        guard !core.isEmpty else { return Parts(prefix: "", word: buffer, punctuation: "") }
        if !prefix.isEmpty, validConversion(core) {
            return Parts(prefix: prefix, word: core, punctuation: "")
        }
        var punctuation = ""
        while let last = core.last, ambiguous(last) {
            punctuation.insert(core.removeLast(), at: punctuation.startIndex)
            // Keep the longest recognized word: yj;. is нож. rather than но;.
            if !core.isEmpty, validConversion(core) {
                return Parts(prefix: prefix, word: core, punctuation: punctuation)
            }
        }
        // Unknown words still retain literal trailing punctuation, including
        // when dictionary validation of corrections is disabled.
        return core.isEmpty ? Parts(prefix: "", word: buffer, punctuation: "")
            : Parts(prefix: prefix, word: core, punctuation: punctuation)
    }
}


/// Serializes edits, including stop/restart while a delayed edit is pending.
struct ReplacementSession {
    private var generation = 0
    private(set) var isBusy = false
    mutating func begin() -> Int? {
        guard !isBusy else { return nil }
        generation &+= 1
        isBusy = true
        return generation
    }
    /// Acceptance has no pending delimiter to wait for. Only a committed edit
    /// may consume the key; failures leave it available to the editor.
    mutating func performImmediately(_ edit: () -> Bool) -> Bool {
        guard let operation = begin() else { return false }
        defer { finish(operation) }
        return edit()
    }

    func isCurrent(_ operation: Int) -> Bool { isBusy && operation == generation }
    mutating func finish(_ operation: Int) {
        if isCurrent(operation) { isBusy = false }
    }
    mutating func cancel() {
        generation &+= 1
        isBusy = false
    }
}


/// Coalesces caret refreshes and makes dismissal cancel pending work.
@MainActor
final class AutocompletionRefresh {
    private var revision = 0

    func cancel() {
        revision &+= 1
    }

    func schedule(delay: Double = 0.150, _ refresh: @escaping @MainActor () -> Void) {
        cancel()
        if delay <= 0 {
            refresh()
            return
        }
        let scheduledRevision = revision
        DispatchQueue.main.asyncAfter(deadline: .now() + delay) { [weak self] in
            guard let self, self.revision == scheduledRevision else { return }
            refresh()
        }
    }
}


/// A continuation replaces the preceding accepted word plus its separator with
/// that same anchor and the next insertion, preserving all accepted text.
struct PhraseAcceptancePlan {
    let expected: String
    let replacement: String

    /// A same-layout completion can be committed without selecting typed text.
    var appendingSuffix: String? {
        guard replacement.hasPrefix(expected) else { return nil }
        return String(replacement.dropFirst(expected.count))
    }

    init(buffer: String, continuationAnchor: String?, insertion: String) {
        if buffer.isEmpty, let anchor = continuationAnchor {
            expected = anchor
            // Restore a word boundary before numbers, quoted words and symbols
            // too. Deferred punctuation such as ", next" must remain attached.
            let firstToken = insertion.prefix(while: { !$0.isWhitespace })
            let startsWord = firstToken.contains { $0.isLetter || $0.isNumber || $0.isSymbol }
            let needsSeparator = anchor.last?.isWhitespace == false && startsWord && !insertion.hasPrefix(" ")
            replacement = anchor + (needsSeparator ? " " : "") + insertion
        } else if !buffer.isEmpty, insertion.hasPrefix(" "), !insertion.hasPrefix(buffer) {
            // Buffer is complete (e.g. "Как") and insertion starts with a leading space (" правильно "):
            expected = buffer
            replacement = buffer + insertion
        } else {
            expected = buffer
            replacement = insertion
        }
    }
}

/// Debounces background AI continuation tasks and cancels them on new keystrokes.
@MainActor
final class AIDebounceTimer {
    private var revision = 0
    private var currentTask: Task<Void, Never>?

    func cancel() {
        revision &+= 1
        currentTask?.cancel()
        currentTask = nil
    }

    func schedule(delay: Double, action: @escaping @MainActor () async -> Void) {
        cancel()
        let scheduledRevision = revision
        currentTask = Task { @MainActor in
            try? await Task.sleep(nanoseconds: UInt64(delay * 1_000_000_000))
            guard !Task.isCancelled, self.revision == scheduledRevision else { return }
            await action()
        }
    }
}


/// Text at a manual activation point is not necessarily a word still being typed.
struct CompletionTypingContext {
    let prefix: String
    let previousWord: String?

    init(beforeCaret: String) {
        let words = beforeCaret.split(whereSeparator: { $0.isWhitespace }).map(String.init)
        if let last = beforeCaret.last, last.isLetter || last.isNumber {
            prefix = words.last ?? ""
            previousWord = words.dropLast().last?.lowercased()
        } else {
            prefix = ""
            previousWord = words.last?.lowercased()
        }
    }
}

struct CompletionAppPauses {
    private var deadlines: [String: Date] = [:]

    func isPaused(bundleID: String?, now: Date) -> Bool {
        guard let bundleID, let until = deadlines[bundleID] else { return false }
        return now < until
    }

    @discardableResult
    mutating func toggle(bundleID: String, now: Date) -> Bool {
        if isPaused(bundleID: bundleID, now: now) {
            deadlines.removeValue(forKey: bundleID)
            return false
        }
        deadlines[bundleID] = now.addingTimeInterval(300)
        return true
    }
}

/// A missing AX receipt does not prove that a dispatched paste failed. Replaying
/// its acceptance key could navigate away after the editor inserted the text.
enum CompletionPasteOutcome {
    case notDispatched, unconfirmed, applied

    var shouldReplayShortcut: Bool { self == .notDispatched }
}

/// Split at word boundaries while preserving punctuation for a later acceptance.
struct CompletionAcceptanceText {
    let insertion: String
    let remaining: String?

    init(candidate: String, typedPrefix: String, entirePhrase: Bool,
         appendSpace: Bool, includePunctuation: Bool) {
        guard !entirePhrase else {
            insertion = candidate + (appendSpace ? " " : "")
            remaining = nil
            return
        }
        let hasLeadingSpace = candidate.hasPrefix(" ")
        var words = candidate.split(separator: " ", omittingEmptySubsequences: true).map(String.init)
        guard !words.isEmpty else { insertion = ""; remaining = nil; return }
        var first = words.removeFirst()
        if !typedPrefix.isEmpty, first.lowercased() == typedPrefix.lowercased(), !words.isEmpty {
            let next = words.removeFirst()
            first += (next.allSatisfy({ $0.isPunctuation }) ? "" : " ") + next
        }
        var deferred = ""
        if !includePunctuation, first.contains(where: { $0.isLetter || $0.isNumber }) {
            while let last = first.last, last.isPunctuation {
                deferred.insert(first.removeLast(), at: deferred.startIndex)
            }
        } else if includePunctuation, let next = words.first,
                  next.allSatisfy({ $0.isPunctuation }) {
            first += words.removeFirst()
        }
        if !deferred.isEmpty, !typedPrefix.isEmpty, first.lowercased() == typedPrefix.lowercased() {
            // The word is already complete. Accept the missing punctuation as
            // its own step instead of attempting an empty append and passing Tab.
            first += deferred
            deferred = ""
        }
        if !deferred.isEmpty { words.insert(deferred, at: 0) }
        let punctuationPending = !includePunctuation && words.first?.first?.isPunctuation == true
        let leading = (hasLeadingSpace && !first.hasPrefix(" ")) ? " " : ""
        let trailing = (appendSpace && !punctuationPending) ? " " : ""
        insertion = leading + first + trailing
        remaining = words.isEmpty ? nil : words.joined(separator: " ")
    }
}

