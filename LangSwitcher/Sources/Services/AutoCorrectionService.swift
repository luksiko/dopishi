import Foundation
import AppKit
import Carbon

// MARK: - Auto-Correction Service
// Monitors keystrokes in real-time and auto-corrects words typed in the wrong
// keyboard layout when the user presses Space, Enter, or punctuation.
//
// Architecture:
//   1. CGEvent tap intercepts keyDown events globally
//   2. Characters are accumulated in a word buffer
//   3. On word boundary (space/enter/punctuation):
//      a. Check if the buffered word looks like wrong layout
//      b. Convert the word using LayoutMapper
//      c. Optionally validate the converted word via NSSpellChecker
//      d. Replace the word using backspace + clipboard paste
//   4. Buffer is cleared and the cycle restarts

@MainActor
final class AutoCorrectionService {

    /// Marker set on synthetic CGEvents generated by AutoCorrectionService to avoid feedback loop
    nonisolated static let syntheticEventMarker: Int64 = 0x4C535749 // 'LSWI'

    // MARK: - Dependencies

    private let settingsManager: SettingsManager
    private let textConverter: TextConverter
    private let accessibilityService: AccessibilityService
    private let spellCheckService: SpellCheckService

    // MARK: - State

    private var wordBuffer: String = ""
    private var isProcessingCorrection = false
    private var eventTap: CFMachPort?
    private var runLoopSource: CFRunLoopSource?

    /// True if the event tap is currently running
    var isRunning: Bool {
        eventTap != nil
    }

    // MARK: - Init

    init(settingsManager: SettingsManager,
         textConverter: TextConverter,
         accessibilityService: AccessibilityService = AccessibilityService(),
         spellCheckService: SpellCheckService = .shared) {
        self.settingsManager = settingsManager
        self.textConverter = textConverter
        self.accessibilityService = accessibilityService
        self.spellCheckService = spellCheckService
    }

    deinit {
        if let tap = eventTap {
            CGEvent.tapEnable(tap: tap, enable: false)
            if let source = runLoopSource {
                CFRunLoopRemoveSource(CFRunLoopGetMain(), source, .commonModes)
            }
            CFMachPortInvalidate(tap)
        }
    }

    // MARK: - Public API

    /// Start monitoring keystrokes for auto-correction.
    /// Requires Accessibility permissions (same as existing hotkey functionality).
    func start() {
        guard eventTap == nil else {
            NSLog("[LangSwitcher] AutoCorrectionService: already started")
            return
        }

        // We need a pointer to self for the C callback.
        // Use Unmanaged to pass self as void pointer.
        let selfPtr = Unmanaged.passUnretained(self).toOpaque()

        // Create event tap listening to keyDown and mouse click events.
        // Using .defaultTap so it works under Accessibility permissions (listenOnly requires Input Monitoring).
        let eventMask: CGEventMask = (1 << CGEventType.keyDown.rawValue) |
                                     (1 << CGEventType.leftMouseDown.rawValue) |
                                     (1 << CGEventType.rightMouseDown.rawValue)

        guard let tap = CGEvent.tapCreate(
            tap: .cgSessionEventTap,
            place: .headInsertEventTap,
            options: .defaultTap,
            eventsOfInterest: eventMask,
            callback: autoCorrectionEventCallback,
            userInfo: selfPtr
        ) else {
            NSLog("[LangSwitcher] AutoCorrectionService: failed to create CGEvent tap. Check Accessibility permissions.")
            return
        }

        eventTap = tap

        let source = CFMachPortCreateRunLoopSource(kCFAllocatorDefault, tap, 0)
        runLoopSource = source
        CFRunLoopAddSource(CFRunLoopGetMain(), source, .commonModes)
        CGEvent.tapEnable(tap: tap, enable: true)

        NSLog("[LangSwitcher] AutoCorrectionService: started keystroke monitoring")
    }

    /// Re-enable the event tap if disabled by system
    func reEnableEventTap() {
        if let tap = eventTap {
            CGEvent.tapEnable(tap: tap, enable: true)
            NSLog("[LangSwitcher] AutoCorrectionService: re-enabled event tap after system disable")
        }
    }

    /// Stop monitoring keystrokes.
    func stop() {
        if let tap = eventTap {
            CGEvent.tapEnable(tap: tap, enable: false)
            if let source = runLoopSource {
                CFRunLoopRemoveSource(CFRunLoopGetMain(), source, .commonModes)
            }
            // CFMachPort is managed by the system, invalidate it
            CFMachPortInvalidate(tap)
            eventTap = nil
            runLoopSource = nil
        }
        wordBuffer = ""
        NSLog("[LangSwitcher] AutoCorrectionService: stopped")
    }

    /// Restart monitoring (e.g., when settings change).
    func restart() {
        stop()
        if settingsManager.autoCorrectionEnabled {
            start()
        }
    }

    // MARK: - Event Handling (called from C callback on main thread)

    /// Reset word buffer when user clicks with mouse
    func handleMouseDown() {
        wordBuffer = ""
    }

    /// Process a keyDown event. Dispatches to MainActor via DispatchQueue.main.async to guarantee FIFO order.
    nonisolated func handleKeyEvent(_ event: CGEvent) {
        let keyCode = event.getIntegerValueField(.keyboardEventKeycode)
        let flags = event.flags
        let characters = getCharactersFromEvent(event)

        DispatchQueue.main.async { [weak self] in
            self?.processKey(keyCode: UInt16(keyCode), flags: flags, characters: characters)
        }
    }

    // MARK: - Key Processing

    private func processKey(keyCode: UInt16, flags: CGEventFlags, characters: String?) {
        // Skip if auto-correction is disabled
        guard settingsManager.autoCorrectionEnabled else { return }

        // Ignore events with Command modifier (⌘C, ⌘V, etc.)
        if flags.contains(.maskCommand) {
            wordBuffer = ""
            return
        }

        // Handle special keys
        switch keyCode {
        case 0x33: // Backspace
            if !wordBuffer.isEmpty {
                wordBuffer.removeLast()
            }
            return

        case 0x7B, 0x7C, 0x7D, 0x7E: // Arrow keys (left, right, down, up)
            wordBuffer = ""
            return

        case 0x35: // Escape
            wordBuffer = ""
            return

        case 0x30: // Tab
            wordBuffer = ""
            return

        case 0x24: // Return/Enter
            // Clear buffer on Enter to avoid racing with form submissions/chat sends
            wordBuffer = ""
            return

        case 0x31: // Space
            triggerCheckAndCorrect(triggerChar: " ")
            return

        default:
            break
        }

        // Get the typed character
        guard let chars = characters, !chars.isEmpty else { return }

        let char = chars.first!

        // Check if it's a word boundary (punctuation)
        if !char.isLetter && !char.isNumber {
            triggerCheckAndCorrect(triggerChar: char)
            return
        }

        // Accumulate character in word buffer
        wordBuffer.append(char)
    }

    // MARK: - Auto-Correction Logic

    /// Check the buffered word and correct it if it looks like wrong layout.
    private func triggerCheckAndCorrect(triggerChar: Character) {
        let word = wordBuffer
        wordBuffer = ""

        // Skip triggering a new correction if one is already in flight
        guard !isProcessingCorrection else { return }

        // Need at least 2 characters to make a meaningful correction
        guard word.count >= 2 else { return }


        NSLog("[LangSwitcher] AutoCorrection: checking word '\(word)' (trigger='\(triggerChar)')")

        // Step 1: Check if the word looks like it was typed in the wrong layout
        guard textConverter.looksLikeWrongLayout(word) else {
            NSLog("[LangSwitcher] AutoCorrection: '\(word)' does not look like wrong layout")
            return
        }

        // Step 2: Convert the word
        guard let result = textConverter.convertSelectedTextWithInfo(word) else {
            NSLog("[LangSwitcher] AutoCorrection: conversion failed for '\(word)'")
            return
        }

        let convertedWord = result.text
        NSLog("[LangSwitcher] AutoCorrection: '\(word)' → '\(convertedWord)'")

        // Step 3: Validate with spell checker (reduce false positives)
        if settingsManager.autoCorrectionUseSpellCheck {
            let layouts = settingsManager.enabledLayouts
            let targetLang = layouts.first(where: { $0.id == result.targetLayoutID })?.languageCode

            if let lang = targetLang {
                // Check if converted word is valid in target language
                if !spellCheckService.isValidWord(convertedWord, language: lang) {
                    NSLog("[LangSwitcher] AutoCorrection: '\(convertedWord)' not valid in '\(lang)', skipping")
                    return
                }
            }

            // Also check if original word IS valid in some language — if so, don't correct
            let sourceLangs = layouts.map(\.languageCode)
            if spellCheckService.isValidWordInAnyLanguage(word, languages: sourceLangs) {
                NSLog("[LangSwitcher] AutoCorrection: '\(word)' is valid in source language, skipping")
                return
            }
        }

        // Step 4: Perform the replacement
        NSLog("[LangSwitcher] AutoCorrection: replacing '\(word)' with '\(convertedWord)'")
        performReplacement(originalWord: word, correctedWord: convertedWord, triggerChar: triggerChar)

        // Step 5: Switch layout if needed
        if settingsManager.autoCorrectionSwitchLayout {
            KeyboardLayoutDetector.switchToLayout(result.targetLayoutID)
        }

        // Step 6: Play feedback
        if settingsManager.playSounds {
            NSSound(named: .init("Tink"))?.play()
        }

        // Step 7: Increment conversion counter
        settingsManager.incrementConversionCount()
    }

    /// Replace the last typed word with the corrected version.
    /// Strategy: send marked backspaces to delete word + trigger char, then paste marked corrected text + trigger.
    private func performReplacement(originalWord: String, correctedWord: String, triggerChar: Character) {
        isProcessingCorrection = true

        // Number of characters to delete: the word + the trigger character that was already typed
        let deleteCount = originalWord.count + 1

        // Set up the corrected text on clipboard
        let pasteboard = NSPasteboard.general
        let savedContents = savePasteboard()

        let replacementText = correctedWord + String(triggerChar)
        pasteboard.clearContents()
        pasteboard.setString(replacementText, forType: .string)

        // Mark pasteboard items as transient/auto-generated so clipboard managers (Raycast, Alfred, Maccy) ignore them
        let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
        let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
        pasteboard.setString("", forType: transientType)
        pasteboard.setString("", forType: autoGeneratedType)

        // Send backspaces with synthetic event marker
        let source = CGEventSource(stateID: .hidSystemState)
        for _ in 0..<deleteCount {
            if let downEvent = CGEvent(keyboardEventSource: source, virtualKey: 0x33, keyDown: true),
               let upEvent = CGEvent(keyboardEventSource: source, virtualKey: 0x33, keyDown: false) {
                downEvent.flags = []
                upEvent.flags = []
                downEvent.setIntegerValueField(.eventSourceUserData, value: AutoCorrectionService.syntheticEventMarker)
                upEvent.setIntegerValueField(.eventSourceUserData, value: AutoCorrectionService.syntheticEventMarker)
                downEvent.post(tap: .cgAnnotatedSessionEventTap)
                upEvent.post(tap: .cgAnnotatedSessionEventTap)
            }
        }

        // Small non-blocking delay for backspaces to process in target app, then paste
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.04) { [weak self] in
            guard let self = self else { return }

            // Paste: Cmd+V with synthetic event marker
            if let downEvent = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: true),
               let upEvent = CGEvent(keyboardEventSource: source, virtualKey: 0x09, keyDown: false) {
                downEvent.flags = .maskCommand
                upEvent.flags = .maskCommand
                downEvent.setIntegerValueField(.eventSourceUserData, value: AutoCorrectionService.syntheticEventMarker)
                upEvent.setIntegerValueField(.eventSourceUserData, value: AutoCorrectionService.syntheticEventMarker)
                downEvent.post(tap: .cgAnnotatedSessionEventTap)
                upEvent.post(tap: .cgAnnotatedSessionEventTap)
            }

            // Restore clipboard and reset state after target app has read from pasteboard
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.25) { [weak self] in
                self?.restorePasteboard(savedContents)
                self?.isProcessingCorrection = false
            }
        }
    }

    // MARK: - Character Extraction

    /// Extract typed characters from a CGEvent.
    nonisolated private func getCharactersFromEvent(_ event: CGEvent) -> String? {
        var length = 0
        event.keyboardGetUnicodeString(maxStringLength: 0, actualStringLength: &length, unicodeString: nil)
        guard length > 0 else { return nil }

        var buffer = [UniChar](repeating: 0, count: length)
        event.keyboardGetUnicodeString(maxStringLength: length, actualStringLength: &length, unicodeString: &buffer)
        return String(utf16CodeUnits: buffer, count: length)
    }

    // MARK: - Pasteboard Helpers

    private func savePasteboard() -> [[(NSPasteboard.PasteboardType, Data)]] {
        let pasteboard = NSPasteboard.general
        return pasteboard.pasteboardItems?.map { item in
            item.types.compactMap { type in
                item.data(forType: type).map { (type, $0) }
            }
        } ?? []
    }

    private func restorePasteboard(_ items: [[(NSPasteboard.PasteboardType, Data)]]) {
        guard !items.isEmpty else { return }
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        for itemData in items {
            let item = NSPasteboardItem()
            for (type, data) in itemData {
                item.setData(data, forType: type)
            }
            pasteboard.writeObjects([item])
        }
    }
}

// MARK: - CGEvent Tap Callback

/// C-compatible callback for the CGEvent tap.
/// Must be a free function (not a method) because CGEvent.tapCreate requires a C function pointer.
private func autoCorrectionEventCallback(
    proxy: CGEventTapProxy,
    type: CGEventType,
    event: CGEvent,
    userInfo: UnsafeMutableRawPointer?
) -> Unmanaged<CGEvent>? {

    // Ignore synthetic events generated by our own auto-correction service to prevent feedback loops
    if event.getIntegerValueField(.eventSourceUserData) == AutoCorrectionService.syntheticEventMarker {
        return Unmanaged.passUnretained(event)
    }

    // Handle tap disabled events (system can disable taps under load)
    if type == .tapDisabledByTimeout || type == .tapDisabledByUserInput {
        // Re-enable the tap
        if let userInfo = userInfo {
            let service = Unmanaged<AutoCorrectionService>.fromOpaque(userInfo).takeUnretainedValue()
            // Re-enable asynchronously on MainActor
            Task { @MainActor in
                service.reEnableEventTap()
            }
        }
        return Unmanaged.passUnretained(event)
    }

    guard let userInfo = userInfo else {
        return Unmanaged.passUnretained(event)
    }

    let service = Unmanaged<AutoCorrectionService>.fromOpaque(userInfo).takeUnretainedValue()

    if type == .leftMouseDown || type == .rightMouseDown {
        DispatchQueue.main.async {
            service.handleMouseDown()
        }
        return Unmanaged.passUnretained(event)
    }

    guard type == .keyDown else {
        return Unmanaged.passUnretained(event)
    }

    service.handleKeyEvent(event)

    // Always pass the event through (defaultTap mode)
    return Unmanaged.passUnretained(event)
}
